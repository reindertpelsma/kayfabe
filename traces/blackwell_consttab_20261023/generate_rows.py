"""2026-10-23: generate consttab rows from the two privileged interface measurements."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[2]
data = root / "crates/kf-disp/data"
classes = [line.split("\t") for line in (data / "classes-595.91.07.tsv").read_text().splitlines()]
arrays = {p[1]: (int(p[2]), int(p[3])) for p in classes if len(p) == 4 and p[0] == "A"}
regs = [line.split("\t") for line in (data / "regs-595.91.07.tsv").read_text().splitlines()]
bases = {int(p[4]) for p in regs if len(p) == 5 and p[1:3] == ["F", "NV_PDISP_FE_SW"]}
assert len(bases) == 1
base = bases.pop()
# 2026-11-03: GB203 added (own Vast lease 58957600, RTX 5070 Ti, kit a6456796e; equal to GB202 on all
# 48 words and 328 decoded fields: traces/blackwell_hw_20261103/gb203_tier3/compare_vs_gb202.txt).
# 2026-11-04: GB205 added (own Vast lease 59031353, RTX 5070 10de:2f04, kit a6456796e; equal to GB202 on all
# 48 words and 328 decoded fields: traces/die_coverage_20261104/blackwell/gb205/measure/compare_vs_gb202.txt).
inputs = {
    "GB202": ("traces/blackwell_windows_resume_20261023/lease_metadata/precomp_tier3.txt", "2026-10-23"),
    "GB203": ("traces/blackwell_hw_20261103/gb203_tier3/precomp_tier3.txt", "2026-11-03"),
    "GB205": ("traces/die_coverage_20261104/blackwell/gb205/measure/precomp_tier3.txt", "2026-11-04"),
    "GB206": ("traces/blackwell_provider_validation_20261023/lease_metadata/precomp_tier3.txt", "2026-10-23"),
}
rows = []
for die, (evidence, date) in inputs.items():
    seen = set()
    for line in (root / evidence).read_text().splitlines():
        if "\tword\t" not in line:
            continue
        parts = line.split("\t")
        tag = f"measured:{die},595.91.07,{date}"
        assert parts[0] == tag
        fields = dict(part.split("=", 1) for part in parts[2:])
        window, kind = int(fields["window"]), fields["type"]
        assert (window, kind) not in seen and 0 <= window < 8 and kind in "ABCDEF"
        seen.add((window, kind))
        start, stride = arrays[f"NVCA73_PRECOMP_WIN_PIPE_HDR_CAP{kind}"]
        offset = start + stride * window
        assert int(fields["address"], 0) == base + offset
        value = int(fields["value"], 0)
        assert 0 <= value < 2**32
        rows.append(
            "\t".join(
                [
                    f"display.precomp.0xca73.{offset:#06x}",
                    die,
                    "595",
                    "4",
                    "-",
                    f"{value:#010x}",
                    tag,
                    evidence,
                ]
            )
        )
    assert seen == {(window, kind) for window in range(8) for kind in "ABCDEF"}
assert len(rows) == 48 * len(inputs)
header = (
    "# Generated by traces/blackwell_consttab_20261023/generate_rows.py; do not edit.\n"
    "# 2026-10-23: complete privileged public READ32/GLOBAL measurements, no capture source.\n"
    "# 2026-11-03: GB203 measured on its own die (lease 58957600); an exact row precedes inheritance.\n"
    "# 2026-11-04: GB205 measured on its own die (lease 59031353); an exact row precedes inheritance.\n"
    "# Branch names the measured HOST driver; these are physical PRECOMP register facts.\n"
    "key\tdie\tbranch\tsize\tinputs\twords\tsource\tevidence\n"
)
out = root / "crates/kf-rm/data/precomp_measured.tsv"
out.write_text(header + "\n".join(rows) + "\n")
print(json.dumps({"rows": len(rows), "output": str(out.relative_to(root))}))
