// Build the status pages' SYNTHETIC fixture (site/status/fixture.json) by sending fixed GET
// requests through the real API handler over the seeded database. The fixture maps an API path
// (with its query string) to the JSON body the API returned. Deterministic: the committed file
// must equal a fresh run (test/fixture.test.js).
//   node scripts/make-fixture.mjs            # print
//   node scripts/make-fixture.mjs --write    # update site/status/fixture.json
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { api } from '../test/helpers.js';
import { syntheticRows } from './seed-data.mjs';
import { SUITES } from '../src/validate.js';

export const FIXTURE_PATH = new URL('../../../site/status/fixture.json', import.meta.url);

export async function buildFixture() {
  const rows = syntheticRows();
  // LOGS_BASE stays empty: fixture output must not contain any deployment URL.
  const { call } = api({ env: { LOGS_BASE: '' } });
  const responses = {};
  const get = async (path) => {
    const r = await call(path);
    if (r.status !== 200) throw new Error('fixture request failed: ' + path + ' ' + r.status);
    responses[path] = r.body;
    return r.body;
  };
  await get('/v1/matrix');
  for (const family of ['turing', 'ampere', 'ada', 'hopper', 'blackwell'])
    await get('/v1/matrix?family=' + family);
  await get('/v1/dies');
  await get('/v1/hosts');
  for (const die of rows.dies)
    for (const suite of SUITES) await get('/v1/cells/' + die.id + '/' + suite.id);
  for (const run of rows.runs) await get('/v1/runs/' + run.id);
  for (const commit of rows.commits) await get('/v1/commits/' + commit.sha + '/requirements');
  return {
    synthetic: true,
    note:
      'SYNTHETIC fixture generated by ci/platform-api/scripts/make-fixture.mjs from ' +
      'scripts/seed-data.mjs. Not measured; no run, revision or box behind any row.',
    responses,
  };
}

export function serialize(fixture) {
  return JSON.stringify(fixture) + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = serialize(await buildFixture());
  if (process.argv.includes('--write')) writeFileSync(FIXTURE_PATH, text);
  else process.stdout.write(text);
}
