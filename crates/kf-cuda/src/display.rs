    /// The pack's host-side bounds: the geometry is re-derived, the layout must be a permutation,
    /// the extent must fit the slot, the staging frame must hold the frame.
    #[test]
    fn a_pack_launch_is_bounded_before_it_is_queued() {
        let hd = BlPack {
            width: 1920,
            height: 1080,
            gobs_per_row: 120,
            h_log2: 4,
            gobs: 9 * 120 * 16,
            bits: [4, 5, 6, 7, 8],
        };
        let slot = 10 << 20;
        let staging = 1920 * 1080 * 4;
        assert_eq!(hd.check(slot, staging), Ok(()));
        assert!(hd.check(8_847_359, staging).is_err(), "one byte short");
        assert!(hd.check(slot, staging - 1).is_err(), "short staging");
        for bad in [
            BlPack {
                gobs_per_row: 121,
                ..hd
            },
            BlPack {
                gobs: hd.gobs + 1,
                ..hd
            },
            BlPack {
                bits: [4, 4, 6, 7, 8],
                ..hd
            },
            BlPack {
                bits: [3, 5, 6, 7, 8],
                ..hd
            },
            BlPack { h_log2: 6, ..hd },
            BlPack { width: 0, ..hd },
        ] {
            assert!(bad.check(slot, staging).is_err(), "{bad:?}");
        }
    }

    /// The host-side bounds of a compose launch: reads in the layer's extent, writes in the frame.
    #[test]
    fn a_compose_launch_is_bounded_before_it_is_queued() {
        let bl = ComposeLayer {
            src: 0,
            extent: 9 * 120 * 16 * 512,
            block_linear: true,
            pitch: 120,
            block_height_log2: 4,
            x0_bytes: 0,
            y0: 0,
            width: 1920,
            rows: 1080,
            ox: 0,
            oy: 0,
            flags: 4,
            a_s: 255,
            b_s: 0,
            a_d: 0,
            b_d: 0,
        };
        assert_eq!(bl.check(1920, 1080), Ok(()));
        assert!(bl.check(1919, 1080).is_err(), "wider than the frame");
        let mut t = bl;
        t.extent -= 1;
        assert!(t.check(1920, 1080).is_err(), "one byte short of the blocks");
        let mut t = bl;
        t.pitch = 119;
        assert!(t.check(1920, 1080).is_err(), "rows wider than the surface");
        let mut t = bl;
        (t.ox, t.width) = (1800, 250);
        assert!(
            t.check(1920, 1080).is_err(),
            "unclipped past the right edge"
        );
        let p = ComposeLayer {
            block_linear: false,
            pitch: 7680,
            extent: 1079 * 7680 + 7680,
            ..bl
        };
        assert_eq!(p.check(1920, 1080), Ok(()));
        let mut t = p;
        t.pitch = 7676;
        assert!(t.check(1920, 1080).is_err(), "a row wider than the pitch");
        // §O: the XOR bit is known; a bit beyond it is refused
        assert_eq!(ComposeLayer { flags: 8, ..p }.check(1920, 1080), Ok(()));
        assert!(
            ComposeLayer { flags: 16, ..p }.check(1920, 1080).is_err(),
            "an unknown flag"
        );
    }
