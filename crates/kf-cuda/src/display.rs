impl DisplayGpu {
    /// Bring up a context on the GPU at PCI address `bdf` (the device's host GPU, never ordinal 0).
    ///
    /// # Errors
    /// [`CudaError`], by name.
    pub fn bring_up_on(bdf: &str) -> Result<DisplayGpu, CudaError> {
        let cu = Cuda::open()?;
        cu.init()?;
        let device = cu.device_by_pci_bus_id(bdf)?;
        let ctx = cu.ctx_create(device)?;
        let stream = cu.stream_create()?;
        let done = CompletionFd::new()?;
        let mut ptx = SCANOUT_PTX.to_vec();
        ptx.push(0);
        let compose = cu
            .module_load(&ptx)
            .and_then(|m| cu.module_function(m, COMPOSE_ENTRY))
            .map_err(|e| format!("the compose kernel did not load: {e}"));
        let mut pack_ptx = PACK_PTX.to_vec();
        pack_ptx.push(0);
        let pack = cu
            .module_load(&pack_ptx)
            .and_then(|m| cu.module_function(m, PACK_ENTRY))
            .map_err(|e| format!("the pack kernel did not load: {e}"));
        let mut sum_ptx = SUM_PTX.to_vec();
        sum_ptx.push(0);
        let sum = cu
            .module_load(&sum_ptx)
            .and_then(|m| cu.module_function(m, SUM_ENTRY))
            .map_err(|e| format!("the checksum kernel did not load: {e}"));
        let mut color_ptx = COLOR_PTX.to_vec();
        color_ptx.push(0);
        let color = cu
            .module_load(&color_ptx)
            .and_then(|m| {
                Ok([
                    cu.module_function(m, "kf_color_compose")?,
                    cu.module_function(m, "kf_color_output")?,
                    cu.module_function(m, "kf_color_validate")?,
                    cu.module_function(m, "kf_tmo_validate")?,
                ])
            })
            .map_err(|e| format!("the SDR colour kernels did not load: {e}"));
        let mut yuv_ptx = YUV_PTX.to_vec();
        yuv_ptx.push(0);
        let yuv = cu
            .module_load(&yuv_ptx)
            .and_then(|m| {
                Ok([
                    cu.module_function(m, YUV_ENTRY)?,
                    cu.module_function(m, YUV_COLOR_ENTRY)?,
                ])
            })
            .map_err(|e| format!("the YUV kernel did not load: {e}"));
        let color_event = cu.event_create()?;
        let signal_event = cu.event_create()?;
        Ok(DisplayGpu {
            cu,
            ctx,
            device,
            store: None,
            stream,
            done,
            compose,
            staging: None,
            pack,
            slots: Vec::new(),
            sum,
            sums: None,
            color,
            yuv,
            color_frame: None,
            color_luts: None,
            color_pipelines: None,
            color_status: None,
            color_event,
            color_recorded: false,
            color_snapshots: [None; 65],
            signal_event,
        })
    }

    /// Why the checksum kernel is unavailable, if it is (the worker logs it once and sends every
    /// check).
    #[must_use]
    pub fn checksum_refused(&self) -> Option<&str> {
        self.sum.as_ref().err().map(String::as_str)
    }

    /// ★ `display-max-fps` (D2): queue the checksum of the `w` x `h` composition begun by
    /// [`Self::compose_begin`] — the row slots zeroed, `kf_sum` over the staging frame (one CTA per
    /// row), the row sums copied back to page-locked memory — on the display stream, without the
    /// signal. [`Self::checksum_rows`] reads them once the frame's completion was observed.
    ///
    /// ⊘ Bounds, here and not in the kernel: the frame lies inside the staging allocation
    /// (`rows x 4w` bytes are read), and the row buffers hold `h` sums (`h x 8` bytes written).
    ///
    /// # Errors
    /// Refused by name: no kernel, no composition, a frame larger than the staging one; the CUDA
    /// error.
    pub fn compose_checksum(&mut self, w: u32, h: u32) -> Result<(), CudaError> {
        let what = "DisplayGpu::compose_checksum";
        let f = *self.sum.as_ref().map_err(|e| refused(what, e.clone()))?;
        let Some((src, len)) = self.staging else {
            return Err(refused(what, "no composition was begun".into()));
        };
        let n = usize::try_from(u64::from(w) * u64::from(h) * 4)
            .map_err(|_| refused(what, format!("{w}x{h}")))?;
        if w == 0 || h == 0 || n > len {
            return Err(refused(
                what,
                format!("a {w}x{h} frame in a {len:#x}-byte staging frame"),
            ));
        }
        let rows = h as usize;
        if self.sums.as_ref().is_none_or(|s| s.2 < rows) {
            if let Some((p, host, _)) = self.sums.take() {
                // the stream drains first: a queued checksum may still write either buffer
                self.cu.ctx_synchronize()?;
                self.cu.mem_free(p);
                self.cu
                    .pinned_free(host, "cuMemFreeHost(display checksum)")?;
            }
            let dev = self
                .cu
                .mem_alloc_zeroed(rows * 8, "cuMemAlloc(display checksum)")?;
            let host = match self
                .cu
                .pinned_alloc(rows * 8, "cuMemAllocHost(display checksum)")
            {
                Ok(h) => h,
                Err(e) => {
                    self.cu.mem_free(dev);
                    return Err(e);
                }
            };
            self.sums = Some((dev, host, rows));
        }
        let Some((dev, host, _)) = self.sums.as_ref() else {
            return Err(refused(what, "no row buffer".into()));
        };
        self.cu.memset_d8_async(
            self.stream,
            *dev,
            0,
            rows * 8,
            "cuMemsetD8Async(display checksum)",
        )?;
        let u = |x: u32| x.to_le_bytes().to_vec();
        let mut params = vec![
            src.to_le_bytes().to_vec(),
            dev.to_le_bytes().to_vec(),
            u(w),
            u(w * 4),
        ];
        self.cu
            .launch_args(self.stream, f, h, SUM_THREADS, 0, &mut params, what)?;
        self.cu.memcpy_d2h_async(
            self.stream,
            host,
            0,
            *dev,
            rows * 8,
            "cuMemcpyDtoHAsync(display checksum)",
        )
    }

    /// ★ The row sums the last [`Self::compose_checksum`] of an `h`-row frame copied back (fold
    /// them with `kf_disp::pace::digest`). ⊘ Only after the completion signal queued behind it was
    /// observed: before, the bytes are still being written by DMA.
    ///
    /// # Errors
    /// Refused when no checksum of that many rows was queued.
    pub fn checksum_rows(&self, h: u32) -> Result<Vec<u64>, CudaError> {
        let what = "DisplayGpu::checksum_rows";
        let rows = h as usize;
        let Some((_, host, cap)) = self.sums.as_ref().filter(|s| s.2 >= rows && rows > 0) else {
            return Err(refused(what, format!("no checksum of {h} rows was queued")));
        };
        debug_assert!(*cap >= rows);
        Ok(host
            .read(0, rows * 8)
            .as_chunks::<8>()
            .0
            .iter()
            .map(|c| u64::from_le_bytes(*c))
            .collect())
    }

    /// Allocate a page-locked frame of `len` bytes in this context.
    ///
    /// # Errors
    /// [`CudaError`]; a zero length is refused.
    pub fn frame(&self, len: usize) -> Result<Frame, CudaError> {
        if len == 0 {
            return Err(refused("DisplayGpu::frame", "a zero-length frame".into()));
        }
        self.make_current()?;
        Ok(Frame {
            buf: self.cu.pinned_alloc(len, "cuMemAllocHost(display frame)")?,
            map: None,
        })
    }

    /// ★ A frame over `map` (the display broker's sealed memfd, mapped by the caller), page-locked
    /// with `cuMemHostRegister` so the scanout copy lands in the pages the broker reads.
    ///
    /// # Errors
    /// The CUDA refusal — a driver without the entry, or one that will not pin these pages — with
    /// the mapping handed back.
    pub fn frame_over(
        &self,
        map: kf_linux_raw::MappedRegion,
    ) -> Result<Frame, (CudaError, kf_linux_raw::MappedRegion)> {
        if let Err(e) = self.make_current() {
            return Err((e, map));
        }
        match self
            .cu
            .host_register(&map.host_span(), "cuMemHostRegister(display broker frame)")
        {
            Ok(buf) => Ok(Frame {
                buf,
                map: Some(map),
            }),
            Err(e) => Err((e, map)),
        }
    }

    /// The fd that becomes readable when a queued scanout copy completed (the worker polls it).
    #[must_use]
    pub fn completion_fd(&self) -> &CompletionFd {
        &self.done
    }

    /// ★ Give a frame back (`cuMemFreeHost`). ⊘ Only once no queued copy targets it and the console
    /// no longer reads it — the caller's frame state machine decides that, never this binding.
    ///
    /// # Errors
    /// [`CudaError`].
    pub fn release_frame(&self, mut f: Frame) -> Result<(), CudaError> {
        self.make_current()?;
        let buf = std::mem::replace(&mut f.buf, PinnedBuf::empty());
        match f.map.take() {
            // unregister first, and the mapping goes only once that succeeded
            Some(map) => {
                let r = self
                    .cu
                    .host_unregister(buf, "cuMemHostUnregister(display broker frame)");
                if r.is_ok() {
                    drop(map);
                } else {
                    std::mem::forget(map);
                }
                r
            }
            None => self.cu.pinned_free(buf, "cuMemFreeHost(display frame)"),
        }
    }

    /// ★ Start a `w` x `h` composition: the device staging frame (grown when too small) cleared to
    /// black on the display stream — what no window covers is black, as on a real head.
    ///
    /// # Errors
    /// [`CudaError`]; an empty or oversized frame is refused.
    pub fn compose_begin(&mut self, w: u32, h: u32) -> Result<(), CudaError> {
        let what = "DisplayGpu::compose_begin";
        let n = usize::try_from(u64::from(w) * u64::from(h) * 4)
            .map_err(|_| refused(what, format!("{w}x{h}")))?;
        if n == 0 || w > 16384 || h > 16384 {
            return Err(refused(what, format!("a {w}x{h} frame")));
        }
        if self.staging.is_none_or(|(_, len)| len < n) {
            if let Some((p, _)) = self.staging.take() {
                // the stream drains first: a queued compose may still write the old staging
                self.cu.ctx_synchronize()?;
                self.cu.mem_free(p);
            }
            self.staging = Some((
                self.cu.mem_alloc_zeroed(n, "cuMemAlloc(display staging)")?,
                n,
            ));
        }
        let (p, _) = self.staging.unwrap_or((0, 0));
        self.cu
            .memset_d8_async(self.stream, p, 0, n, "cuMemsetD8Async(display staging)")
    }

    /// ★ Queue window `l` of the composition begun by [`Self::compose_begin`] (`w` x `h`).
    ///
    /// # Errors
    /// Refused by name when the kernel did not load, a read would leave the store or the layer's
    /// extent, or a write the frame; the CUDA error otherwise.
    pub fn compose_layer(&self, l: &ComposeLayer, w: u32, h: u32) -> Result<(), CudaError> {
        let what = "DisplayGpu::compose_layer";
        l.check(w, h).map_err(|e| refused(what, e))?;
        let n = usize::try_from(l.extent).map_err(|_| refused(what, format!("{l:?}")))?;
        let src = self.at(l.src, n, what)?;
        self.launch_compose(src, l, w, h, what)
    }

    /// ★ Is the YUV kernel loaded? (When not, the console copy leaves YUV windows out, by name.)
    ///
    /// # Errors
    /// Why it did not load.
    pub fn yuv_ready(&self) -> Result<(), String> {
        self.yuv.as_ref().map(|_| ()).map_err(Clone::clone)
    }

    /// ★ Queue one semi-planar YUV window onto the composition begun by [`Self::compose_begin`]
    /// (opaque, after whatever was composed before it).
    ///
    /// # Errors
    /// Refused by name when the kernel did not load, a read would leave a plane's extent or the
    /// store, or a write the frame; the CUDA error otherwise.
    pub fn compose_yuv(&self, l: &YuvLayer, w: u32, h: u32) -> Result<(), CudaError> {
        let what = "DisplayGpu::compose_yuv";
        let f = self.yuv.as_ref().map_err(|e| refused(what, e.clone()))?[0];
        l.check(w, h).map_err(|e| refused(what, e))?;
        let Some((dst, _)) = self.staging else {
            return Err(refused(what, "no composition was begun".into()));
        };
        self.launch_yuv(f, dst, l, w, h, what)
    }

    /// ★ The same window into the colour composition's FP32 frame ([`Self::color_begin`]), in its
    /// place in the back-to-front order (opaque; the window's own colour pipeline is not applied).
    ///
    /// # Errors
    /// As [`Self::compose_yuv`].
    pub fn color_yuv(&self, l: &YuvLayer, w: u32, h: u32) -> Result<(), CudaError> {
        let what = "DisplayGpu::color_yuv";
        let f = self.yuv.as_ref().map_err(|e| refused(what, e.clone()))?[1];
        l.check(w, h).map_err(|e| refused(what, e))?;
        let (dst, len) = self
            .color_frame
            .ok_or_else(|| refused(what, "no colour frame".into()))?;
        if u64::from(w) * u64::from(h) * 16 > len as u64 {
            return Err(refused(what, "colour frame is too small".into()));
        }
        self.launch_yuv(f, dst, l, w, h, what)
    }

    fn launch_yuv(
        &self,
        f: Func,
        dst: CUdeviceptr,
        l: &YuvLayer,
        w: u32,
        h: u32,
        what: &'static str,
    ) -> Result<(), CudaError> {
        let ny = usize::try_from(l.y_extent).map_err(|_| refused(what, format!("{l:?}")))?;
        let nc = usize::try_from(l.c_extent).map_err(|_| refused(what, format!("{l:?}")))?;
        let ys = self.at(l.y_src, ny, what)?;
        let cs = self.at(l.c_src, nc, what)?;
        let u = |x: u32| x.to_le_bytes().to_vec();
        let mut params = vec![
            ys.to_le_bytes().to_vec(),
            cs.to_le_bytes().to_vec(),
            dst.to_le_bytes().to_vec(),
            u(u32::from(l.block_linear)),
            u(l.y_pitch),
            u(l.c_pitch),
            u(l.block_height_log2),
            u(l.sx0),
            u(l.sy0),
            u(l.sw),
            u(l.sh),
            u(l.ox),
            u(l.oy),
            u(l.dw),
            u(l.dh),
            u(w),
            u(h),
            u(l.sub_x_log2),
            u(l.sub_y_log2),
            u(u32::from(l.vu_first)),
        ];
        self.cu
            .launch_args(self.stream, f, l.dh, 256, 0, &mut params, what)
    }

    /// Begin a colour composition, retaining FP16 values in an FP32 container until output.
    /// All operations are on the display worker's stream, away from the vCPU.
    pub fn color_begin(&mut self, w: u32, h: u32) -> Result<(), CudaError> {
        self.color_recorded = false;
        let what = "DisplayGpu::color_begin";
        if u64::from(w) * u64::from(h) > 3840 * 2160 {
            return Err(refused(
                what,
                "SDR frame exceeds fixed 4K pixel ceiling".into(),
            ));
        }
        self.color.as_ref().map_err(|e| refused(what, e.clone()))?;
        self.compose_begin(w, h)?;
        let n = w as usize * h as usize * 16;
        if self.color_frame.is_none_or(|(_, len)| len < n) {
            if let Some((p, _)) = self.color_frame.take() {
                self.cu.ctx_synchronize()?;
                self.cu.mem_free(p);
            }
            self.color_frame = Some((self.cu.mem_alloc_zeroed(n, what)?, n));
        }
        if self.color_luts.is_none() {
            self.color_luts = Some(self.cu.mem_alloc_zeroed(65 * COLOR_LUT_BYTES, what)?);
        }
        if self.color_pipelines.is_none() {
            self.color_pipelines = Some(self.cu.mem_alloc_zeroed(32 * COLOR_PIPELINE_BYTES, what)?);
        }
        if self.color_status.is_none() {
            let dev = self.cu.mem_alloc_zeroed(4, what)?;
            match self.cu.pinned_alloc(4, what) {
                Ok(host) => self.color_status = Some((dev, host)),
                Err(e) => {
                    self.cu.mem_free(dev);
                    return Err(e);
                }
            }
        }
        let (frame, _) = self
            .color_frame
            .ok_or_else(|| refused(what, "missing colour frame".into()))?;
        let (status, _) = self
            .color_status
            .as_ref()
            .ok_or_else(|| refused(what, "missing colour status".into()))?;
        self.cu.memset_d8_async(self.stream, *status, 0, 4, what)?;
        self.cu.memset_d8_async(self.stream, frame, 0, n, what)
    }

    fn color_snapshot(
        &mut self,
        slot: u32,
        lut: Option<ColorLut>,
        input: bool,
    ) -> Result<CUdeviceptr, CudaError> {
        let what = "DisplayGpu::color_snapshot";
        let Some(lut) = lut else {
            return Ok(0);
        };
        if slot > 64 {
            return Err(refused(what, "LUT slot outside fixed allocation".into()));
        }
        if !(65..=1025).contains(&lut.entries)
            || ((input || slot == 64) && ![257, 1025].contains(&lut.entries))
        {
            return Err(refused(
                what,
                "LUT sample count outside supported extent".into(),
            ));
        }
        let bytes = (lut.entries as usize + 4) * 8;
        let src = self.at(lut.src, bytes, what)?;
        let base = self
            .color_luts
            .ok_or_else(|| refused(what, "no LUT allocation".into()))?;
        let dst = base + u64::from(slot) * COLOR_LUT_BYTES as u64;
        let key = (lut.src, lut.interpolate, lut.token, lut.entries);
        if self.color_snapshots[slot as usize]
            .is_none_or(|old| (old.src, old.interpolate, old.token, old.entries) != key)
        {
            self.cu
                .memcpy_d2d_async(self.stream, dst, src, bytes, what)?;
            self.color_snapshots[slot as usize] = Some(lut);
        }
        if input {
            let f = self.color.as_ref().map_err(|e| refused(what, e.clone()))?[2];
            let status = self
                .color_status
                .as_ref()
                .ok_or_else(|| refused(what, "no validation status".into()))?
                .0;
            let mut args = vec![
                dst.to_le_bytes().to_vec(),
                lut.entries.to_le_bytes().to_vec(),
                status.to_le_bytes().to_vec(),
            ];
            self.cu
                .launch_args(self.stream, f, 5, 256, 0, &mut args, what)?;
        }
        Ok(dst)
    }

    /// Snapshot and compose one RGB8888 window using its FP16 input table.
    /// Convenience entry for SDR fixtures with the remaining stages bypassed.
    pub fn color_layer(
        &mut self,
        slot: u32,
        l: &ComposeLayer,
        lut: Option<ColorLut>,
        w: u32,
        h: u32,
    ) -> Result<(), CudaError> {
        self.color_pipeline_layer(slot, l, lut, None, None, w, h)
    }

    /// Run the complete authored pre-composition program on the GPU. TMO snapshots
    /// use separate slots; no source reread or fabricated GPU completion is introduced.
    #[allow(clippy::too_many_arguments)]
    pub fn color_pipeline_layer(
        &mut self,
        slot: u32,
        l: &ComposeLayer,
        lut: Option<ColorLut>,
        tmo: Option<ColorLut>,
        pipeline: Option<&ColorPipeline>,
        w: u32,
        h: u32,
    ) -> Result<(), CudaError> {
        let what = "DisplayGpu::color_layer";
        l.check(w, h).map_err(|e| refused(what, e))?;
        if slot >= 32 || l.flags & 8 != 0 {
            return Err(refused(
                what,
                "window slot or XOR outside SDR subset".into(),
            ));
        }
        let src = self.at(
            l.src,
            usize::try_from(l.extent).map_err(|_| refused(what, "layer extent".into()))?,
            what,
        )?;
        let bytes = u64::from(w) * u64::from(h) * 16;
        let (dst, len) = self
            .color_frame
            .ok_or_else(|| refused(what, "no colour frame".into()))?;
        if bytes > len as u64 {
            return Err(refused(what, "colour frame is too small".into()));
        }
        let p = self.color_snapshot(slot, lut, true)?;
        let tone = self.color_snapshot(32 + slot, tmo, false)?;
        if let Some(tmo) = tmo {
            let f = self.color.as_ref().map_err(|e| refused(what, e.clone()))?[3];
            let status = self
                .color_status
                .as_ref()
                .ok_or_else(|| refused(what, "missing status".into()))?
                .0;
            let mut args = vec![
                tone.to_le_bytes().to_vec(),
                tmo.entries.to_le_bytes().to_vec(),
                status.to_le_bytes().to_vec(),
            ];
            self.cu
                .launch_args(self.stream, f, 5, 256, 0, &mut args, what)?;
        }
        let program = if let Some(pipeline) = pipeline {
            let bytes = pipeline.bytes().map_err(|e| refused(what, e))?;
            let address = self
                .color_pipelines
                .ok_or_else(|| refused(what, "missing pipeline allocation".into()))?
                + u64::from(slot) * COLOR_PIPELINE_BYTES as u64;
            self.cu.memcpy_h2d(address, &bytes, what)?;
            address
        } else {
            0
        };
        let f = self.color.as_ref().map_err(|e| refused(what, e.clone()))?[0];
        let u = |v: u32| v.to_le_bytes().to_vec();
        let i = |v: i32| v.to_le_bytes().to_vec();
        let mut args = vec![
            src.to_le_bytes().to_vec(),
            dst.to_le_bytes().to_vec(),
            u(u32::from(l.block_linear)),
            u(l.pitch),
            u(l.block_height_log2),
            u(l.x0_bytes),
            u(l.y0),
            u(l.width),
            u(l.ox),
            u(l.oy),
            u(w),
            u(h),
            u(l.flags),
            i(l.a_s),
            i(l.b_s),
            i(l.a_d),
            i(l.b_d),
            p.to_le_bytes().to_vec(),
            u(u32::from(lut.is_some_and(|v| v.interpolate))),
            u(lut.map_or(0, |v| v.entries)),
            tone.to_le_bytes().to_vec(),
            u(u32::from(tmo.is_some_and(|v| v.interpolate))),
            u(tmo.map_or(0, |v| v.entries)),
            program.to_le_bytes().to_vec(),
            self.color_status
                .as_ref()
                .ok_or_else(|| refused(what, "missing status".into()))?
                .0
                .to_le_bytes()
                .to_vec(),
        ];
        self.cu
            .launch_args(self.stream, f, l.rows, 256, 0, &mut args, what)
    }

    /// Apply the authored CSC coefficients and the fixed-point output table to the full head.
    /// The validation result is copied back on this same stream, before the frame's signal.
    pub fn color_output(
        &mut self,
        w: u32,
        h: u32,
        lut: Option<ColorLut>,
        matrix: &[i32; 12],
    ) -> Result<(), CudaError> {
        let what = "DisplayGpu::color_output";
        let (src, slen) = self
            .color_frame
            .ok_or_else(|| refused(what, "no colour frame".into()))?;
        let (dst, dlen) = self
            .staging
            .ok_or_else(|| refused(what, "no output frame".into()))?;
        let pixels = u64::from(w) * u64::from(h);
        if w == 0 || h == 0 || pixels * 16 > slen as u64 || pixels * 4 > dlen as u64 {
            return Err(refused(what, "colour output exceeds frame".into()));
        }
        let p = self.color_snapshot(64, lut, false)?;
        let f = self.color.as_ref().map_err(|e| refused(what, e.clone()))?[1];
        let mut args = vec![
            src.to_le_bytes().to_vec(),
            dst.to_le_bytes().to_vec(),
            w.to_le_bytes().to_vec(),
            p.to_le_bytes().to_vec(),
            u32::from(lut.is_some_and(|v| v.interpolate))
                .to_le_bytes()
                .to_vec(),
            matrix.iter().flat_map(|v| v.to_le_bytes()).collect(),
            lut.map_or(0, |v| v.entries).to_le_bytes().to_vec(),
        ];
        self.cu
            .launch_args(self.stream, f, h, 256, 0, &mut args, what)?;
        let (dev, host) = self
            .color_status
            .as_ref()
            .ok_or_else(|| refused(what, "no validation status".into()))?;
        self.cu
            .memcpy_d2h_async(self.stream, host, 0, *dev, 4, what)?;
        self.cu.event_record(self.color_event, self.stream)?;
        self.color_recorded = true;
        Ok(())
    }

    /// Read only after the actual GPU completion signal. Never exposes LUT bytes to the CPU.
    pub fn color_verdict(&self) -> Result<(), String> {
        if !self.color_recorded
            || !self
                .cu
                .event_query(self.color_event)
                .map_err(|e| e.to_string())?
        {
            return Err("colour validation has not completed on the GPU".into());
        }
        let (_, host) = self
            .color_status
            .as_ref()
            .ok_or("no colour validation result")?;
        let b = host.read(0, 4);
        if b == [0, 0, 0, 0] {
            Ok(())
        } else {
            Err(if b[0] & 1 != 0 {
                "input LUT has non-SDR FP16 entries"
            } else if b[0] & 2 != 0 {
                "TMO LUT has unsupported VSS header or unequal intensity channels"
            } else {
                "CSC program produced nonfinite FP16"
            }
            .into())
        }
    }

    /// ★ End the composition: the staging frame is copied into `dst` (tight, `w * 4` bytes a row),
    /// then the host signal on [`Self::completion_fd`]. Only the GPU moves the bytes.
    ///
    /// # Errors
    /// Refused by name when the frame is smaller than the composition; the CUDA error otherwise.
    pub fn compose_finish(&self, w: u32, h: u32, dst: &Frame) -> Result<(), CudaError> {
        self.compose_to_host(w, h, dst)?;
        self.compose_signal()
    }

    /// ★ The host signal on [`Self::completion_fd`], after whatever the frame's last operation
    /// was (the D2H copy, the pack, or both) — queued once per frame.
    ///
    /// # Errors
    /// The CUDA error.
    pub fn compose_signal(&self) -> Result<(), CudaError> {
        self.cu.event_record(self.signal_event, self.stream)?;
        self.cu.launch_host_signal(self.stream, &self.done)
    }

    /// ★ 2026-10-08 (`V3_DISPLAY.md` §8.18): the state of the work before the last
    /// [`Self::compose_signal`] — **never blocks**. `Ok(false)`: still queued (the GPU, or the host
    /// RM in front of it, has not run it yet); `Ok(true)`: done, its signal is on its way; `Err`:
    /// the stream failed, by name — the only answer that means the completion will never come.
    ///
    /// # Errors
    /// The CUDA error the stream reports.
    pub fn signal_state(&self) -> Result<bool, CudaError> {
        self.cu.event_query(self.signal_event)
    }

    /// ★ The staging frame's D2H copy into `dst` (tight, `w * 4` bytes a row), without the signal
    /// — the host-RAM rungs and the console.
    ///
    /// # Errors
    /// Refused by name when the frame is smaller than the composition; the CUDA error otherwise.
    pub fn compose_to_host(&self, w: u32, h: u32, dst: &Frame) -> Result<(), CudaError> {
        let what = "DisplayGpu::compose_to_host";
        let n = usize::try_from(u64::from(w) * u64::from(h) * 4)
            .map_err(|_| refused(what, format!("{w}x{h}")))?;
        let Some((p, len)) = self.staging else {
            return Err(refused(what, "no composition was begun".into()));
        };
        if n > len || n > dst.len() {
            return Err(refused(what, format!("{n:#x} bytes do not fit")));
        }
        self.cu.memcpy_d2h_async(
            self.stream,
            &dst.buf,
            0,
            p,
            n,
            "cuMemcpyDtoHAsync(display frame)",
        )
    }

    /// ★ The GPU-copy rung: the staging frame PACKED into slot `slot` (block-linear, `pack`'s
    /// geometry), without the signal. No byte crosses PCIe. The bounds are [`BlPack::check`]'s,
    /// against this slot's own length and the staging frame's.
    ///
    /// # Errors
    /// Refused by name: no pack kernel, an unknown slot, no composition, a bound; the CUDA error.
    pub fn compose_to_slot(&self, slot: SlotId, pack: &BlPack) -> Result<(), CudaError> {
        let what = "DisplayGpu::compose_to_slot";
        let Some((src, staging_bytes)) = self.staging else {
            return Err(refused(what, "no composition was begun".into()));
        };
        self.launch_pack(src, staging_bytes as u64, slot, pack, what)
    }

    /// The pack launch: [`BlPack::check`] first, then `ceil(gobs / 8)` CTAs of 256 threads.
    fn launch_pack(
        &self,
        src: CUdeviceptr,
        src_bytes: u64,
        slot: SlotId,
        pack: &BlPack,
        what: &'static str,
    ) -> Result<(), CudaError> {
        let f = *self.pack.as_ref().map_err(|e| refused(what, e.clone()))?;
        let Some(&(dst, bytes)) = self.slots.get(slot.0) else {
            return Err(refused(what, format!("{slot:?} was never imported")));
        };
        pack.check(bytes, src_bytes).map_err(|e| refused(what, e))?;
        let grid = u32::try_from(pack.gobs.div_ceil(u64::from(PACK_THREADS / 32)))
            .map_err(|_| refused(what, format!("{pack:?}: too many GOBs")))?;
        let u = |x: u32| x.to_le_bytes().to_vec();
        let mut params = vec![
            src.to_le_bytes().to_vec(),
            dst.to_le_bytes().to_vec(),
            u(pack.width),
            u(pack.height),
            u(pack.gobs_per_row),
            u(pack.h_log2),
            pack.gobs.to_le_bytes().to_vec(),
            u(pack.bits[0]),
            u(pack.bits[1]),
            u(pack.bits[2]),
            u(pack.bits[3]),
            u(pack.bits[4]),
        ];
        self.cu
            .launch_args(self.stream, f, grid, PACK_THREADS, 0, &mut params, what)
    }

    /// ★ Import a display slot — the RM object `fd` (an `/dev/nvidiactl` descriptor RM exported it
    /// on) of `bytes` bytes — into this context, exactly as the store is imported. `bytes` must be
    /// whole 2 MiB granules (CUDA maps imports in its allocation granularity).
    ///
    /// # Errors
    /// Refused by name for a bad size; the import step that refused.
    pub fn import_slot(&mut self, fd: i32, bytes: u64) -> Result<SlotId, CudaError> {
        let what = "DisplayGpu::import_slot";
        if bytes == 0 || !bytes.is_multiple_of(2 << 20) || bytes > 64 << 20 {
            return Err(refused(what, format!("a {bytes:#x}-byte slot")));
        }
        self.make_current()?;
        let n = usize::try_from(bytes).map_err(|_| refused(what, format!("{bytes:#x}")))?;
        let p = self
            .cu
            .import_and_map(self.device, fd, n)
            .map_err(|name| CudaError::Refused {
                what: "cuMemImportFromShareableHandle + cuMemMap (display slot)",
                code: 0,
                name,
            })?;
        self.slots.push((p, bytes));
        Ok(SlotId(self.slots.len() - 1))
    }

    /// ★ Zero slot `slot` (synchronously) — before it is ever exported, so a compositor can never
    /// see what the previous tenant of that VRAM left.
    ///
    /// # Errors
    /// Refused for an unknown slot; the CUDA error.
    pub fn zero_slot(&self, slot: SlotId) -> Result<(), CudaError> {
        let what = "DisplayGpu::zero_slot";
        let Some(&(p, bytes)) = self.slots.get(slot.0) else {
            return Err(refused(what, format!("{slot:?} was never imported")));
        };
        let n = usize::try_from(bytes).map_err(|_| refused(what, format!("{bytes:#x}")))?;
        self.make_current()?;
        self.cu.memset_d8(p, 0, n, "cuMemsetD8(display slot)")
    }

    /// The bytes of slot `slot`.
    #[must_use]
    pub fn slot_bytes(&self, slot: SlotId) -> Option<u64> {
        self.slots.get(slot.0).map(|s| s.1)
    }

    /// ★ Bring-up self-test of the pack kernel on SYNTHETIC data, into a slot that has NOT been
    /// exported yet: `staging` (`4·w·h` bytes) is uploaded to scratch, packed into `slot`, and the
    /// slot's first `pack.gobs * 512` bytes come back for the caller to compare with
    /// `kf_disp::vramslot::pack_reference`. The slot is zeroed again afterwards.
    ///
    /// # Errors
    /// [`CudaError`]; a bound [`BlPack::check`] refuses.
    pub fn selftest_bl_pack(
        &mut self,
        slot: SlotId,
        staging: &[u8],
        pack: &BlPack,
    ) -> Result<Vec<u8>, CudaError> {
        let what = "DisplayGpu::selftest_bl_pack";
        self.make_current()?;
        let Some(&(p, bytes)) = self.slots.get(slot.0) else {
            return Err(refused(what, format!("{slot:?} was never imported")));
        };
        pack.check(bytes, staging.len() as u64)
            .map_err(|e| refused(what, e))?;
        let ext = usize::try_from(pack.gobs * 512).map_err(|_| refused(what, "extent".into()))?;
        let scratch = self
            .cu
            .mem_alloc_zeroed(staging.len(), "cuMemAlloc(pack selftest)")?;
        let out = (|| {
            self.cu
                .memcpy_h2d(scratch, staging, "cuMemcpyHtoD(pack selftest)")?;
            self.launch_pack(scratch, staging.len() as u64, slot, pack, what)?;
            self.cu.ctx_synchronize()?;
            let mut back = vec![0u8; ext];
            self.cu
                .memcpy_d2h(&mut back, p, "cuMemcpyDtoH(pack selftest)")?;
            Ok(back)
        })();
        self.cu.mem_free(scratch);
        let zeroed = self.zero_slot(slot);
        let out = out?;
        zeroed?;
        Ok(out)
    }

    /// The compose kernel launch (one CTA per row, 256 threads striding the row).
    fn launch_compose(
        &self,
        src: CUdeviceptr,
        l: &ComposeLayer,
        w: u32,
        h: u32,
        what: &'static str,
    ) -> Result<(), CudaError> {
        let f = *self
            .compose
            .as_ref()
            .map_err(|e| refused(what, e.clone()))?;
        let Some((dst, _)) = self.staging else {
            return Err(refused(what, "no composition was begun".into()));
        };
        let u = |x: u32| x.to_le_bytes().to_vec();
        let i = |x: i32| x.to_le_bytes().to_vec();
        let mut params = vec![
            src.to_le_bytes().to_vec(),
            dst.to_le_bytes().to_vec(),
            u(u32::from(l.block_linear)),
            u(l.pitch),
            u(l.block_height_log2),
            u(l.x0_bytes),
            u(l.y0),
            u(l.width),
            u(l.ox),
            u(l.oy),
            u(w * 4),
            u(w),
            u(h),
            u(l.flags),
            i(l.a_s),
            i(l.b_s),
            i(l.a_d),
            i(l.b_d),
        ];
        self.cu
            .launch_args(self.stream, f, l.rows, 256, 0, &mut params, what)
    }

    /// ★ Bring-up self-test of the compose kernel on SYNTHETIC data (never guest memory): upload
    /// `surface` to a scratch allocation, compose layer `l` (its `src` is ignored) into a `w` x `h`
    /// frame, wait, and return the frame's bytes — the caller compares them with the reference.
    ///
    /// # Errors
    /// [`CudaError`]; a layer that leaves `surface` or the frame is refused.
    pub fn selftest_compose(
        &mut self,
        surface: &[u8],
        l: &ComposeLayer,
        w: u32,
        h: u32,
    ) -> Result<Vec<u8>, CudaError> {
        let what = "DisplayGpu::selftest_compose";
        if l.extent > surface.len() as u64 {
            return Err(refused(what, format!("{l:?} leaves the synthetic surface")));
        }
        l.check(w, h).map_err(|e| refused(what, e))?;
        self.make_current()?;
        let len = usize::try_from(u64::from(w) * u64::from(h) * 4)
            .map_err(|_| refused(what, format!("{w}x{h}")))?;
        let scratch = self
            .cu
            .mem_alloc_zeroed(surface.len(), "cuMemAlloc(compose selftest)")?;
        let out = (|| {
            self.cu
                .memcpy_h2d(scratch, surface, "cuMemcpyHtoD(compose selftest)")?;
            let frame = self.frame(len)?;
            let run = self
                .compose_begin(w, h)
                .and_then(|()| self.launch_compose(scratch, l, w, h, what))
                .and_then(|()| {
                    let (p, _) = self.staging.unwrap_or((0, 0));
                    self.cu.memcpy_d2h_async(
                        self.stream,
                        &frame.buf,
                        0,
                        p,
                        len,
                        "cuMemcpyDtoHAsync(compose selftest)",
                    )
                })
                .and_then(|()| self.cu.ctx_synchronize());
            let bytes = run.map(|()| frame.read(0, len));
            let freed = self.release_frame(frame);
            let bytes = bytes?;
            freed?;
            Ok(bytes)
        })();
        self.cu.mem_free(scratch);
        out
    }

    /// Hardware oracle on synthetic fixtures only. The temporary store contains no
    /// guest data; table bytes are uploaded, snapshotted and transformed on the GPU.
    /// A rejected FP16 table returns an error before any fixture pixels are read.
    pub fn selftest_color(&mut self, fixture: &ColorFixture<'_>) -> Result<Vec<u8>, CudaError> {
        let what = "DisplayGpu::selftest_color";
        let ColorFixture {
            surface,
            input,
            output,
            layer,
            matrix,
            size: (w, h),
            ..
        } = *fixture;
        if ![261 * 8, COLOR_LUT_BYTES].contains(&input.len())
            || ![261 * 8, COLOR_LUT_BYTES].contains(&output.len())
            || surface.is_empty()
            || !surface.len().is_multiple_of(8)
            || layer.extent > surface.len() as u64
            || fixture.tone.is_some_and(|t| {
                !(69 * 8..=COLOR_LUT_BYTES).contains(&t.table.len())
                    || !t.table.len().is_multiple_of(8)
                    || t.mutate.is_some_and(|v| v.len() != t.table.len())
            })
            || fixture.mutate_input.is_some_and(|b| b.len() != input.len())
        {
            return Err(refused(what, "synthetic fixture extent".into()));
        }
        layer.check(w, h).map_err(|e| refused(what, e))?;
        self.make_current()?;
        self.cu.ctx_synchronize()?;
        let mut image = surface.to_vec();
        image.extend_from_slice(input);
        image.extend_from_slice(output);
        let tone_src = image.len() as u64;
        if let Some(tone) = fixture.tone {
            image.extend_from_slice(tone.table);
        }
        let scratch = self.cu.mem_alloc_zeroed(image.len(), what)?;
        let keep = self.store.replace((scratch, image.len() as u64));
        self.color_snapshots.fill(None);
        let run = (|| {
            self.cu.memcpy_h2d(scratch, &image, what)?;
            self.color_begin(w, h)?;
            let mut l = *layer;
            l.src = 0;
            let input_lut = Some(ColorLut {
                entries: (input.len() / 8 - 4) as u32,
                src: surface.len() as u64,
                interpolate: false,
                token: 1,
            });
            let tone_lut = fixture.tone.map(|t| ColorLut {
                entries: (t.table.len() / 8 - 4) as u32,
                src: tone_src,
                interpolate: true,
                token: 4,
            });
            self.color_pipeline_layer(
                0,
                &l,
                input_lut,
                tone_lut,
                fixture.tone.map(|t| t.pipeline),
                w,
                h,
            )?;
            if let Some(tone) = fixture.tone
                && let Some(new) = tone.mutate
            {
                self.cu.ctx_synchronize()?;
                self.cu.memcpy_h2d(scratch + tone_src, new, what)?;
                self.color_begin(w, h)?;
                self.color_pipeline_layer(
                    0,
                    &l,
                    input_lut,
                    Some(ColorLut {
                        entries: (tone.table.len() / 8 - 4) as u32,
                        src: tone_src,
                        interpolate: true,
                        token: if tone.rearm { 5 } else { 4 },
                    }),
                    Some(tone.pipeline),
                    w,
                    h,
                )?;
            }
            if let Some(new) = fixture.mutate_input {
                self.cu.ctx_synchronize()?;
                self.cu
                    .memcpy_h2d(scratch + surface.len() as u64, new, what)?;
                self.color_begin(w, h)?;
                self.color_layer(
                    0,
                    &l,
                    Some(ColorLut {
                        entries: (input.len() / 8 - 4) as u32,
                        src: surface.len() as u64,
                        interpolate: false,
                        token: if fixture.rearm { 3 } else { 1 },
                    }),
                    w,
                    h,
                )?;
            }
            self.color_output(
                w,
                h,
                Some(ColorLut {
                    entries: (output.len() / 8 - 4) as u32,
                    src: (surface.len() + input.len()) as u64,
                    interpolate: fixture.interpolate,
                    token: 2,
                }),
                matrix,
            )?;
            self.cu.ctx_synchronize()?;
            self.color_verdict().map_err(|e| refused(what, e))?;
            let frame = self.frame(w as usize * h as usize * 4)?;
            let copy = self.compose_to_host(w, h, &frame);
            let drained = self.cu.ctx_synchronize();
            if drained.is_err() {
                // A queued DMA may still name this pinned memory; keep it until
                // context destruction rather than freeing it on a lost completion.
                std::mem::forget(frame);
                drained?;
                unreachable!();
            }
            let bytes = copy.map(|()| frame.read(0, frame.len()));
            let freed = self.release_frame(frame);
            let bytes = bytes?;
            freed?;
            Ok(bytes)
        })();
        let drained = self.cu.ctx_synchronize();
        self.store = keep;
        self.color_snapshots.fill(None);
        // On a CUDA fault retain the scratch allocation until context destruction.
        if drained.is_ok() {
            self.cu.mem_free(scratch);
        }
        let bytes = run?;
        drained?;
        Ok(bytes)
    }

    /// Make this context current on the calling thread (the worker calls it once, at its top).
    ///
    /// # Errors
    /// [`CudaError`].
    pub fn make_current(&self) -> Result<(), CudaError> {
        self.cu.ctx_set_current(self.ctx)
    }

    /// Import the RM-exported store (`fd` on `/dev/nvidiactl`, `bytes` long) into this context.
    ///
    /// # Errors
    /// [`CudaError`], naming the import step that refused; a second import is refused.
    pub fn import_store(&mut self, fd: i32, bytes: u64) -> Result<(), CudaError> {
        if self.store.is_some() {
            return Err(refused(
                "DisplayGpu::import_store",
                "a store is already imported".into(),
            ));
        }
        self.make_current()?;
        let n = usize::try_from(bytes).map_err(|_| {
            refused(
                "DisplayGpu::import_store",
                format!("{bytes:#x} does not fit usize"),
            )
        })?;
        let p = self
            .cu
            .import_and_map(self.device, fd, n)
            .map_err(|name| CudaError::Refused {
                what: "cuMemImportFromShareableHandle + cuMemMap (display)",
                code: 0,
                name,
            })?;
        self.store = Some((p, bytes));
        Ok(())
    }

    /// The store address of `[off, off+len)`, refused by name unless wholly inside the store.
    fn at(&self, off: u64, len: usize, what: &'static str) -> Result<CUdeviceptr, CudaError> {
        let Some((base, bytes)) = self.store else {
            return Err(refused(what, "no store imported".into()));
        };
        if off.checked_add(len as u64).is_none_or(|e| e > bytes) {
            return Err(refused(
                what,
                format!("[{off:#x}, +{len:#x}) leaves the {bytes:#x}-byte store"),
            ));
        }
        Ok(base + off)
    }

    /// ★ Read `buf.len()` bytes of the store at `off` — the GPU copies them to host memory (the
    /// display instance memory's context-DMA table, a video-memory semaphore).
    ///
    /// # Errors
    /// Refused by name outside the store; the CUDA error otherwise.
    pub fn read_store(&self, off: u64, buf: &mut [u8]) -> Result<(), CudaError> {
        let src = self.at(off, buf.len(), "DisplayGpu::read_store")?;
        self.cu
            .memcpy_d2h(buf, src, "cuMemcpyDtoH(display read_store)")
    }

    /// ★ Write `bytes` into the store at `off` (a video-memory notifier or semaphore release).
    ///
    /// # Errors
    /// Refused by name outside the store; the CUDA error otherwise.
    pub fn write_store(&self, off: u64, bytes: &[u8]) -> Result<(), CudaError> {
        let dst = self.at(off, bytes.len(), "DisplayGpu::write_store")?;
        self.cu
            .memcpy_h2d(dst, bytes, "cuMemcpyHtoD(display write_store)")
    }

    /// ★ Zero `[off, off+len)` of the store (the guest's display instance memory when it is stated:
    /// the guest never zeroes it, `disp_inst_mem.c:170-201`).
    ///
    /// # Errors
    /// Refused by name outside the store; the CUDA error otherwise.
    pub fn zero_store(&self, off: u64, len: u64) -> Result<(), CudaError> {
        let n = usize::try_from(len)
            .map_err(|_| refused("DisplayGpu::zero_store", format!("{len:#x}")))?;
        let dst = self.at(off, n, "DisplayGpu::zero_store")?;
        self.cu
            .memset_d8(dst, 0, n, "cuMemsetD8(display zero_store)")
    }
}

impl Drop for DisplayGpu {
    fn drop(&mut self) {
        // the stream drains (every queued host signal with it) before the context goes
        self.cu.stream_destroy(self.stream);
        self.cu.event_destroy(self.color_event);
        self.cu.event_destroy(self.signal_event);
        if let Some((p, _)) = self.staging.take() {
            self.cu.mem_free(p);
        }
        // the checksum's page-locked half is the context's, reclaimed with it
        if let Some((p, _, _)) = self.sums.take() {
            self.cu.mem_free(p);
        }
        if let Some((p, _)) = self.color_frame.take() {
            self.cu.mem_free(p);
        }
        if let Some(p) = self.color_luts.take() {
            self.cu.mem_free(p);
        }
        if let Some(p) = self.color_pipelines.take() {
            self.cu.mem_free(p);
        }
        if let Some((p, _)) = self.color_status.take() {
            self.cu.mem_free(p);
        }
        self.cu.ctx_destroy(self.ctx);
    }
}

