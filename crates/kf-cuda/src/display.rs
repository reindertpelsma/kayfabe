/// The most an expanded cursor image takes: 256 x 256 pixels of 4 bytes.
pub const CURSOR_PX_MAX: usize = 256 * 256 * 4;

/// ★ D-11 (security review 2, 2026-11-13; DESIGN, not measured): the most pixels a composition's
/// device staging frame may hold, `3840 x 2160` — the same ceiling as
/// `kf_disp::scanout::MAX_PIXELS`, which the only production caller (kf-qemu's display worker)
/// already enforces before [`DisplayGpu::compose_begin`], and as the colour path's fixed 4K
/// ceiling. 33 MB of device memory instead of the 1 GiB a 16384 x 16384 request used to allocate
/// outside `fb-mb`. A larger request is refused by name.
pub const MAX_STAGING_PIXELS: u64 = 3840 * 2160;

/// ★ D-11 (DESIGN): the most display slots one [`DisplayGpu`] imports. The broker's ring has
/// `kf_broker::slots::MAX_SLOTS` (5) and imports are never unmapped while the device lives, so 16
/// is three times the need; at 64 MiB per slot it bounds the imported VRAM at 1 GiB. The 17th
/// import is refused by name (kf-qemu then withdraws the GPU-copy rung, loudly).
pub const MAX_IMPORTED_SLOTS: usize = 16;

/// The staging frame's bytes for a `w x h` composition, or why it is refused (empty, a side past
/// 16384, or more than [`MAX_STAGING_PIXELS`]).
fn staging_request(w: u32, h: u32) -> Result<usize, String> {
    let pixels = u64::from(w) * u64::from(h);
    if pixels == 0 || w > 16384 || h > 16384 || pixels > MAX_STAGING_PIXELS {
        return Err(format!(
            "a {w}x{h} frame (at most 16384 a side and {MAX_STAGING_PIXELS} pixels, D-11)"
        ));
    }
    usize::try_from(pixels * 4).map_err(|_| format!("{w}x{h}"))
}

/// The bytes of one more imported slot, or why it is refused: not whole 2 MiB granules, more than
/// 64 MiB, or [`MAX_IMPORTED_SLOTS`] already imported (`imported`).
fn slot_request(imported: usize, bytes: u64) -> Result<usize, String> {
    if bytes == 0 || !bytes.is_multiple_of(2 << 20) || bytes > 64 << 20 {
        return Err(format!("a {bytes:#x}-byte slot"));
    }
    if imported >= MAX_IMPORTED_SLOTS {
        return Err(format!(
            "{MAX_IMPORTED_SLOTS} slots are already imported (D-11 cap)"
        ));
    }
    usize::try_from(bytes).map_err(|_| format!("{bytes:#x}"))
}

/// ★★★ D-03 (security review 2, 2026-11-13): the device frame a kernel writes, validated ONCE
/// against the allocation it lands in. A compose/colour kernel bounds its writes by the `w x h` its
/// caller names; this is where that pair is checked against the bytes actually allocated, so a
/// `(w, h)` larger than the frame can only be refused, never become a GPU write past it.
///
/// `frame` is the allocation (`(address, bytes)`), `bpp` the bytes per pixel the kernel writes.
///
/// # Errors
/// Refused by name: no frame, an empty or overflowing `w x h x bpp`, or more bytes than the frame.
fn frame_for<'a>(
    frame: Option<&'a DevBuf>,
    w: u32,
    h: u32,
    bpp: u64,
    what: &'static str,
) -> Result<DevSpan<'a>, CudaError> {
    let Some(buf) = frame else {
        return Err(refused(what, "no composition frame was begun".into()));
    };
    let len = buf.len();
    let need = u64::from(w)
        .checked_mul(u64::from(h))
        .and_then(|p| p.checked_mul(bpp));
    match need {
        // ★ carried as a `DevSpan` of exactly the frame: validated once, here
        Some(n) if n > 0 && n <= len as u64 => Ok(buf.span(0, n as usize)),
        _ => Err(refused(
            what,
            format!(
                "a {w}x{h} frame at {bpp} bytes per pixel does not fit the {len:#x}-byte frame \
                 it would be written into"
            ),
        )),
    }
}

/// ★ One page-locked host frame buffer the display console reads (M2). Its address crosses to the
/// QEMU console as an integer; this crate writes it only through the GPU copy engine.
///
/// Two backings: `cuMemAllocHost` ([`DisplayGpu::frame`], the console alone), or — with the
/// display broker on — a mapping of a sealed memfd the broker also receives, page-locked with
/// `cuMemHostRegister` ([`DisplayGpu::frame_over`]). The frame then OWNS that mapping, so the
/// registration can never outlive the pages it pins.
pub struct Frame {
    buf: PinnedBuf,
    map: Option<kf_linux_raw::MappedRegion>,
}

impl Frame {
    /// Host address of the frame's first byte.
    #[must_use]
    pub fn addr(&self) -> usize {
        self.buf.addr()
    }

    /// Bytes.
    #[must_use]
    pub fn len(&self) -> usize {
        self.buf.len()
    }

    /// Never empty (a zero-length frame is refused at allocation).
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.buf.len() == 0
    }

    /// A copy of `n` bytes at `off` — for a diagnostic digest of a frame whose copy COMPLETED
    /// (the console reads the same bytes to show them). ⊘ Never while a copy targets the frame.
    ///
    /// # Panics
    /// If the range leaves the frame.
    #[must_use]
    pub fn read(&self, off: usize, n: usize) -> Vec<u8> {
        self.buf.read(off, n)
    }
}

impl Drop for Frame {
    fn drop(&mut self) {
        // ⊘ A registered frame dropped WITHOUT `DisplayGpu::release_frame` keeps its pages
        // mapped: the registration must never outlive the mapping it pins.
        if let Some(m) = self.map.take() {
            std::mem::forget(m);
        }
    }
}

impl std::fmt::Debug for Frame {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Frame").field("len", &self.len()).finish()
    }
}

/// Every [`ComposeLayer::flags`] bit `kf_compose` knows: alpha, swap red/blue, opaque, and (§O,
/// 2026-10-04) XOR — `out = below XOR (source & 0x00ffffff)`. A layer with another bit is refused
/// before a launch: the kernel would silently treat it as a blend.
pub const COMPOSE_FLAGS: u32 = 0xf;

/// ★ One window's compose-kernel program (the mirror of `kf_disp::scanout::LayerPlan`): every read
/// is bounded by `extent` inside the store and every write by the frame, before it is queued.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ComposeLayer {
    /// Store offset of the first byte the kernel addresses.
    pub src: u64,
    /// Bytes from `src` the kernel may read.
    pub extent: u64,
    /// Block-linear (else pitch).
    pub block_linear: bool,
    /// Pitch in bytes, or GOBs per row.
    pub pitch: u32,
    /// log2 GOBs per block.
    pub block_height_log2: u32,
    /// The rectangle's first byte column (block-linear).
    pub x0_bytes: u32,
    /// Its first row (block-linear).
    pub y0: u32,
    /// Pixels per row.
    pub width: u32,
    /// Rows.
    pub rows: u32,
    /// Output column in the frame.
    pub ox: u32,
    /// Output row.
    pub oy: u32,
    /// `bit0` alpha, `bit1` swap red/blue, `bit2` opaque, `bit3` XOR ([`COMPOSE_FLAGS`]; the
    /// mirror of `kf_disp::scanout::COMPOSE_*`, pinned equal by kf-qemu).
    pub flags: u32,
    /// Blend coefficients (see `kf_compose`).
    pub a_s: i32,
    /// See `a_s`.
    pub b_s: i32,
    /// See `a_s`.
    pub a_d: i32,
    /// See `a_s`.
    pub b_d: i32,
}

impl ComposeLayer {
    /// ⊘ The kernel's reads stay inside `extent` and its writes inside a `fw` x `fh` frame.
    fn check(&self, fw: u32, fh: u32) -> Result<(), String> {
        let l = *self;
        let fits = |a: u32, n: u32, room: u32| u64::from(a) + u64::from(n) <= u64::from(room);
        if l.rows == 0 || l.width == 0 || l.rows > 16384 || l.width > 16384 {
            return Err(format!("{l:?} is not a composable rectangle"));
        }
        if !fits(l.ox, l.width, fw) || !fits(l.oy, l.rows, fh) {
            return Err(format!("{l:?} leaves the {fw}x{fh} frame"));
        }
        if l.flags & !COMPOSE_FLAGS != 0 {
            return Err(format!("{l:?}: flag bits the kernel does not know"));
        }
        let row = u64::from(l.width) * 4;
        let need = if l.block_linear {
            if l.block_height_log2 > 5
                || !l.x0_bytes.is_multiple_of(4)
                || u64::from(l.x0_bytes) + row > u64::from(l.pitch) * 64
            {
                return Err(format!("{l:?}: the rows leave the surface's GOB columns"));
            }
            (u64::from(l.y0) + u64::from(l.rows)).div_ceil(8u64 << l.block_height_log2)
                * u64::from(l.pitch)
                * (512u64 << l.block_height_log2)
        } else {
            if u64::from(l.pitch) < row {
                return Err(format!("{l:?}: a row is wider than the pitch"));
            }
            u64::from(l.rows - 1) * u64::from(l.pitch) + row
        };
        if need > l.extent {
            return Err(format!("{l:?}: the rows need {need:#x} bytes"));
        }
        Ok(())
    }
}

