/// ★ One pack: a `width`×`height` staging frame into a slot's block-linear extent. The values
/// come from `kf_disp::vramslot::slot_geom` and its `GobLayout`; [`BlPack::check`] re-derives
/// every one of them here before a launch, so a drift between the two crates is a refusal, never
/// an out-of-bounds write.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BlPack {
    /// Pixels per row.
    pub width: u32,
    /// Rows.
    pub height: u32,
    /// GOBs per row.
    pub gobs_per_row: u32,
    /// log2 GOBs per block.
    pub h_log2: u32,
    /// GOBs the extent holds.
    pub gobs: u64,
    /// The in-GOB bits of `y0, y1, x4, y2, x5`.
    pub bits: [u32; 5],
}

impl BlPack {
    /// ⊘ The launch's bounds: the geometry is the one `(width, height, h_log2)` implies, the
    /// layout is a permutation of bits 4..=8, the extent fits `slot_bytes`, and the staging frame
    /// holds `4·w·h` bytes.
    ///
    /// # Errors
    /// The bound that failed, by name.
    pub fn check(&self, slot_bytes: u64, staging_bytes: u64) -> Result<(), String> {
        let p = *self;
        if p.width == 0 || p.height == 0 || p.width > 16384 || p.height > 16384 || p.h_log2 > 5 {
            return Err(format!("{p:?} is not a packable frame"));
        }
        let gpr = (p.width * 4).div_ceil(64);
        let gobs = (u64::from(p.height.div_ceil(8 << p.h_log2)) * u64::from(gpr)) << p.h_log2;
        if p.gobs_per_row != gpr || p.gobs != gobs {
            return Err(format!(
                "{p:?}: a {}x{} frame at 2^{} GOBs a block is {gpr} GOBs a row and {gobs} GOBs",
                p.width, p.height, p.h_log2
            ));
        }
        let mut seen = 0u32;
        for b in p.bits {
            if !(4..=8).contains(&b) || seen & (1 << b) != 0 {
                return Err(format!(
                    "{p:?}: the GOB bits are not a permutation of 4..=8"
                ));
            }
            seen |= 1 << b;
        }
        if gobs * 512 > slot_bytes {
            return Err(format!(
                "{p:?}: {:#x} bytes do not fit the {slot_bytes:#x}-byte slot",
                gobs * 512
            ));
        }
        if u64::from(p.width) * u64::from(p.height) * 4 > staging_bytes {
            return Err(format!(
                "{p:?}: the staging frame holds {staging_bytes:#x} bytes"
            ));
        }
        Ok(())
    }
}

