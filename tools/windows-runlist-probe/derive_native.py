#!/usr/bin/env python3
"""Compile the exact public allocation layout and verify our native class measurement.

Only open headers and published native metadata are inputs. No closed executable
or raw queue body is read. This generates allocation vocabulary, not scheduling.
"""

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tempfile


def verify_capture(path, digest, class_id, size):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"native metadata digest mismatch: {path.name}")
    rows = list(csv.DictReader(io.StringIO(data.decode("utf-8")), delimiter="\t"))
    allocations = [r for r in rows if r["kind"] == "alloc"
                   and int(r["control_or_class"], 0) == class_id]
    commands = [r for r in allocations if r["dir"] == "cmd"]
    replies = [r for r in allocations if r["dir"] == "status"]
    if len(commands) != 4 or len(replies) != 4:
        raise ValueError("requires all four measured allocations and four replies")
    if any(r["decode"] != "ok" or int(r["declared_params_bytes"]) != size
           for r in allocations):
        raise ValueError("allocation declaration disagrees with native metadata")
    for command in commands:
        matches = [r for r in replies if r["source"] == command["source"]
                   and r["instance"] == command["instance"]
                   and r["function"] == command["function"]
                   and r["rpc_sequence"] == command["rpc_sequence"]]
        if len(matches) != 1 or any(int(matches[0][key], 0) != 0
                                   for key in ("rpc_result", "rpc_result_private")):
            raise ValueError("native allocation lacks a unique successful reply")


def provenance_rows(spec):
    """The cell's provenance rows (crate::provenance; V3_PROVENANCE.md sections 1-2).

    The cited lines are the committed excerpt of the verified captures (spec["excerpts"]); the
    test crates/kf-abi/tests/windows_cell_provenance.rs checks that each line shows its needle.
    Line 4 of an excerpt is the first command, line 6 the first successful reply.
    """
    command = "\\t0x67\\t0xffffffff\\t0xffffffff\\t2243\\talloc\\t0xb297\\t-\\t12\\tok"
    reply = "\\t0x67\\t0x0\\t0x0\\t2243\\talloc\\t0xb297\\t-\\t12\\tok"

    def line(name, number, needle):
        return (f'Evidence {{ at: "{spec["excerpts"][name]}:{number}", '
                f'needle: "{needle}" }}')

    both = ("seed", "revisit")
    class_evidence = ", ".join(line(n, k, v) for n in both for k, v in ((4, command), (6, reply)))
    size_evidence = ", ".join(line(n, 4, command) for n in both)
    source = spec["source"]
    return "\n".join([
        f'Row {{ item: "class", source: "{source}", evidence: &[{class_evidence}] }},',
        f'Row {{ item: "params_size", source: "{source}", evidence: &[{size_evidence}] }},',
        'Row { item: "params_layout", source: "ogkm-580.94.02:src/common/sdk/nvidia/inc/nvos.h '
        '(NV_SWRUNLIST_ALLOCATION_PARAMS; offsets compiled by layout.c)", evidence: &[] },',
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ogkm", type=Path, required=True)
    parser.add_argument("--trace-dir", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    spec = json.loads(Path(__file__).with_name("native-58151.json").read_text())
    commit = subprocess.check_output(
        ["git", "-C", str(args.ogkm), "rev-parse", "HEAD"], text=True).strip()
    if commit != spec["public_commit"]:
        raise ValueError("requires exact public OGKM 580.94.02")
    include = "src/common/sdk/nvidia/inc"
    dirty = subprocess.check_output(
        ["git", "-C", str(args.ogkm), "status", "--porcelain",
         "--untracked-files=normal", "--", include], text=True)
    if dirty:
        raise ValueError("public SDK headers must be clean")
    for capture in spec["captures"]:
        verify_capture(args.trace_dir / capture["file"], capture["sha256"],
                       spec["class"], spec["declared_params_bytes"])
    with tempfile.TemporaryDirectory(prefix="kf-native-runlist-layout-") as tmp:
        exe = Path(tmp) / "layout"
        subprocess.run(["cc", "-std=c11", "-Werror", "-I" + str(args.ogkm / include),
                        str(Path(__file__).with_name("layout.c")), "-o", str(exe)], check=True)
        size, engine, max_tsgs, qos = map(
            int, subprocess.check_output([str(exe)], text=True).split())
    if size != spec["declared_params_bytes"]:
        raise ValueError("compiled public layout disagrees with native declared size")
    major, minor, patch = spec["wire_version"]
    rows = provenance_rows(spec)
    args.out.write_text(f'''// @generated by tools/windows-runlist-probe/derive_native.py; do not edit.
// Public layout: OGKM 580.94.02 {commit}, nvos.h.
// Class binding: {spec["source"]}; see tools/windows-runlist-probe/native-58151.json.
// Allocation-only diagnostic; no constructor or scheduling evidence is implied.
use crate::provenance::{{Evidence, Row}};

pub(super) const CELLS: &[super::MeasuredAllocationCell] = &[super::MeasuredAllocationCell {{
    architecture: {spec["architecture"]:#x},
    implementation: {spec["implementation"]},
    allocation: super::AllocationCell {{
        wire_version: crate::DriverVersion {{ major: {major}, minor: {minor}, patch: {patch} }},
        windows_name: "{spec["windows_name"]}",
        class: {spec["class"]:#x},
        size: {size},
        engine: {engine},
        max_tsgs: {max_tsgs},
        qos: {qos},
    }},
    rows: &[
{rows}
    ],
}}];
''')
    subprocess.run(["rustfmt", "--edition", "2024", str(args.out)], check=True)


if __name__ == "__main__":
    main()
