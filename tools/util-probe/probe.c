/* STATUS: LIVE, 2026-11-17 (docs/design/V3_UTILIZATION_FLAG.md).
 *
 * Compiled against one ogkm tree's public SDK headers; prints `kind<TAB>name<TAB>value` lines that
 * generate.py turns into crates/kf-abi/src/utilization_generated.rs. Nothing here is a hand-typed number:
 * every value is `sizeof`, `offsetof` or a macro the header defines. */
#include <stddef.h>
#include <stdio.h>
#include "nvtypes.h"
#include "ctrl/ctrl2080/ctrl2080perf.h"
#include "ctrl/ctrl2080/ctrl2080gpumon.h"
#include "ctrl/ctrl2080/ctrl2080internal.h"
#include "ctrl/ctrl00de.h"
#include "class/cl00de.h"

#define VAL(n) printf("value\t" #n "\t%llu\n", (unsigned long long)(n))
#define SZ(t) printf("sizeof\t" #t "\t%zu\n", sizeof(t))
#define OFF(t, f) printf("field\t" #t "." #f "\t%zu\n", offsetof(t, f))

int main(void)
{
    /* GPUMON: the control, the sample type, the buffer geometry. */
    VAL(NV2080_CTRL_CMD_PERF_GET_GPUMON_PERFMON_UTIL_SAMPLES_V2);
    VAL(NV2080_CTRL_GPUMON_SAMPLE_TYPE_PERFMON_UTIL);
    VAL(NV2080_GPUMON_PID_INVALID);
    VAL(NV2080_CTRL_PERF_GPUMON_SAMPLE_COUNT_PERFMON_UTIL);
    VAL(NV_SUBPROC_NAME_MAX_LENGTH);
    SZ(NV2080_CTRL_PERF_GET_GPUMON_PERFMON_UTIL_SAMPLES_V2_PARAMS);
    OFF(NV2080_CTRL_PERF_GET_GPUMON_PERFMON_UTIL_SAMPLES_V2_PARAMS, type);
    OFF(NV2080_CTRL_PERF_GET_GPUMON_PERFMON_UTIL_SAMPLES_V2_PARAMS, bufSize);
    OFF(NV2080_CTRL_PERF_GET_GPUMON_PERFMON_UTIL_SAMPLES_V2_PARAMS, count);
    OFF(NV2080_CTRL_PERF_GET_GPUMON_PERFMON_UTIL_SAMPLES_V2_PARAMS, tracker);
    OFF(NV2080_CTRL_PERF_GET_GPUMON_PERFMON_UTIL_SAMPLES_V2_PARAMS, samples);
    SZ(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE);
    OFF(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE, base.timeStamp);
    OFF(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE, fb);
    OFF(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE, gr);
    OFF(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE, nvenc);
    OFF(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE, nvdec);
    OFF(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE, nvjpg);
    OFF(NV2080_CTRL_PERF_GPUMON_PERFMON_UTIL_SAMPLE, nvofa);
    SZ(NV2080_CTRL_PERF_GPUMON_ENGINE_UTIL_SAMPLE);
    OFF(NV2080_CTRL_PERF_GPUMON_ENGINE_UTIL_SAMPLE, util);
    OFF(NV2080_CTRL_PERF_GPUMON_ENGINE_UTIL_SAMPLE, vgpuScale);
    OFF(NV2080_CTRL_PERF_GPUMON_ENGINE_UTIL_SAMPLE, procId);
    OFF(NV2080_CTRL_PERF_GPUMON_ENGINE_UTIL_SAMPLE, subProcessID);
    OFF(NV2080_CTRL_PERF_GPUMON_ENGINE_UTIL_SAMPLE, subProcessName);
    OFF(NV2080_CTRL_PERF_GPUMON_ENGINE_UTIL_SAMPLE, pOsPidInfo);

    /* RUSD: the two internal controls, the user class, the polled-utilisation record. */
    VAL(NV2080_CTRL_CMD_INTERNAL_INIT_USER_SHARED_DATA);
    VAL(NV2080_CTRL_CMD_INTERNAL_USER_SHARED_DATA_SET_DATA_POLL);
    VAL(NV00DE_CTRL_CMD_REQUEST_DATA_POLL);
    VAL(RM_USER_SHARED_DATA);
    SZ(NV2080_CTRL_INTERNAL_INIT_USER_SHARED_DATA_PARAMS);
    OFF(NV2080_CTRL_INTERNAL_INIT_USER_SHARED_DATA_PARAMS, bInit);
    OFF(NV2080_CTRL_INTERNAL_INIT_USER_SHARED_DATA_PARAMS, physAddr);
    SZ(NV2080_CTRL_INTERNAL_USER_SHARED_DATA_SET_DATA_POLL_PARAMS);
    OFF(NV2080_CTRL_INTERNAL_USER_SHARED_DATA_SET_DATA_POLL_PARAMS, polledDataMask);
    VAL(NV00DE_RUSD_POLL_PERF);
    VAL(RUSD_TIMESTAMP_INVALID);
    VAL(RUSD_TIMESTAMP_WRITE_IN_PROGRESS);
    VAL(RUSD_ENG_UTILIZATION_VID_ENG_NVENC);
    VAL(RUSD_ENG_UTILIZATION_VID_ENG_NVDEC);
    VAL(RUSD_ENG_UTILIZATION_VID_ENG_NVJPG);
    VAL(RUSD_ENG_UTILIZATION_VID_ENG_NVOFA);
    VAL(RUSD_ENG_UTILIZATION_COUNT);
    SZ(NV00DE_SHARED_DATA);
    OFF(NV00DE_SHARED_DATA, perfDevUtil);
    SZ(RUSD_PERF_DEVICE_UTILIZATION);
    OFF(RUSD_PERF_DEVICE_UTILIZATION, lastModifiedTimestamp);
    OFF(RUSD_PERF_DEVICE_UTILIZATION, info);
    SZ(RUSD_PERF_DEVICE_UTILIZATION_INFO);
    OFF(RUSD_PERF_DEVICE_UTILIZATION_INFO, gpuPercentBusy);
    OFF(RUSD_PERF_DEVICE_UTILIZATION_INFO, memoryPercentBusy);
    OFF(RUSD_PERF_DEVICE_UTILIZATION_INFO, engUtil);
    SZ(RUSD_ENG_UTILIZATION);
    OFF(RUSD_ENG_UTILIZATION, clkPercentBusy);
    OFF(RUSD_ENG_UTILIZATION, samplingPeriodUs);
    return 0;
}
