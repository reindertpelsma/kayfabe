#!/usr/bin/env python3
"""Emit the dedicated compound host-read ABI from public C compiler measurements.

Recompile abi/layout_probe.c against each pinned SDK before updating its TSV/source
receipt. This emitter consumes only those committed measurements, never GPU words.
"""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess

ap = argparse.ArgumentParser()
ap.add_argument('--evidence', type=Path, default=Path('traces/blackwell_host_caps_review_20261022/abi'))
ap.add_argument('--out', type=Path, default=Path('crates/kf-host/src/precomp_layout.rs'))
a = ap.parse_args()
sources = json.loads((a.evidence / 'sources.json').read_text())
profiles = []
for tag, receipt in sources.items():
    raw = (a.evidence / (tag + '.tsv')).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == receipt['output_sha256']
    values = {}
    for line in raw.decode().splitlines():
        kind, name, value, *_ = line.split('\t')
        values[(kind, name)] = int(value)
    profiles.append((tag, values))
assert all(v == profiles[0][1] for _, v in profiles), 'emit distinct layouts when the public ABI changes'
v = profiles[0][1]
p = 'NV2080_CTRL_GPU_EXEC_REG_OPS_PARAMS'
o = 'NV2080_CTRL_GPU_REG_OP'
items = [('param_size', 'sizeof', p), ('op_size', 'sizeof', o), ('count', 'field', p+'.regOpCount'), ('pointer', 'field', p+'.regOps'), ('operation', 'field', o+'.regOp'), ('kind', 'field', o+'.regType'), ('status', 'field', o+'.regStatus'), ('offset', 'field', o+'.regOffset'), ('value', 'field', o+'.regValueLo')]
constants = [('cmd', 'NV2080_CTRL_CMD_GPU_EXEC_REG_OPS'), ('read32', 'NV2080_CTRL_GPU_REG_OP_READ_32'), ('global', 'NV2080_CTRL_GPU_REG_OP_TYPE_GLOBAL'), ('success', 'NV2080_CTRL_GPU_REG_OP_STATUS_SUCCESS'), ('no_access', 'NV2080_CTRL_GPU_REG_OP_STATUS_NOACCESS')]
lines = ['// @generated by tools/derive_precomp_host_layout.py; public C compiler inputs in traces/blackwell_host_caps_review_20261022/abi.', '// Exact SDK membership only; an unknown host gets the derived fallback.', '#[derive(Clone, Copy)]', 'pub(super) struct Layout {']
lines += [f'    pub {name}: usize,' for name, _, _ in items]
lines += ['    pub cmd: u32,'] + [f'    pub {name}: u8,' for name, _ in constants[1:]]
lines += ['}', 'pub(super) fn for_version(version: &str) -> Option<Layout> {', '    match version {', '        ' + ' | '.join(json.dumps(tag) for tag, _ in profiles) + ' => Some(Layout {']
lines += [f'            {name}: {v[(kind, name_c)]},' for name, kind, name_c in items]
lines += [f'            {name}: {v[("value", name_c)]},' for name, name_c in constants]
lines += ['        }),', '        _ => None,', '    }', '}']
a.out.write_text('\n'.join(lines)+'\n')

subprocess.run(['rustfmt', '--edition', '2024', str(a.out)], check=True)
