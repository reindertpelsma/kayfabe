#
# The display link (`crates/kf-rm/src/display.rs`) answers ~30 physical-RM display controls whose
# params are plain C structs in the SDK (`ctrl0073*.h`, `ctrl5070*.h`, `ctrlc370*.h`, `ctrlc372*.h`,
# `nvos.h`). This script asks the COMPILER for each struct's size and each named member's offset and
# size, and for the value of each named constant, and writes one TSV row per fact:
#     SIZE   <struct>                 <sizeof>
#     FIELD  <struct> <member>        <offsetof> <sizeof member>
#     CONST  <name>                   <value>
# `kf_disp::layout` reads the TSV at compile time (include_str!) and refuses a missing name loudly.
# ⚠ Per driver TAG: today 580.159.04 (the bench). The driver matrix (tools/drivermatrix) is where
# these belong once a second guest version needs display — V3_DISPLAY.md §6 risk 6.
#
