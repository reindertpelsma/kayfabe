  echo '#include <stdio.h>'
  echo '#include <stddef.h>'
  echo '#include "nvtypes.h"'
  echo '#include "nvos.h"'
  for h in "$INC"/ctrl/ctrl0073/*.h "$INC"/ctrl/ctrl5070/*.h "$INC"/ctrl/ctrlc370/*.h "$INC"/ctrl/ctrlc372/*.h \
           "$INC"/ctrl/ctrl2080/ctrl2080internal.h; do echo "#include \"$h\""; done
  echo 'int main(void){'
  seen=""
  for f in "${FIELDS[@]}"; do
    s=${f%%:*}; m=${f#*:}
    case " $seen " in *" $s "*) ;; *) echo "  printf(\"SIZE\\t$s\\t%zu\\n\", sizeof($s));"; seen="$seen $s";; esac
    echo "  printf(\"FIELD\\t$s\\t$m\\t%zu\\t%zu\\n\", offsetof($s, $m), sizeof((($s*)0)->$m));"
  done
  for c in "${CONSTS[@]}"; do echo "  printf(\"CONST\\t$c\\t0x%llx\\n\", (unsigned long long)($c));"; done
  echo '  return 0; }'
} > "$tmp/l.c"
