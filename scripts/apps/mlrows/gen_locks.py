"""Regenerate the hashed locks of the three open ML rows with `uv pip compile --generate-hashes` (the same tool and method as kfml's locks).

STATUS: LIVE, 2026-11-17. The digests in a lock are the ones the INDEX publishes for each file: PyPI's own for the PyPI packages, NVIDIA's own index (pypi.nvidia.com) for the
TensorRT wheels. Nothing is hashed by us from a file we host or build. Resolution does not need a GPU or a CUDA machine, only the network and `uv` (pip install uv);
it targets CPython 3.12 on x86_64 glibc 2.34 (`--python-platform x86_64-manylinux_2_34`: llguidance's wheel needs glibc 2.31, Ubuntu 22.04 has 2.35, Ubuntu 24.04 2.39).
A new lock changes what a row installs: re-run `mlrows.py lockcheck`, the GPU-free tests, and a native run, and update pins.json in the same change.

    python3 scripts/apps/mlrows/gen_locks.py [--uv uv] [name ...]       names: vllm_cu13 jax_cu12 jax_cu13 tensorrt_cu12 tensorrt_cu13
"""
import argparse
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
NVIDIA = ["--extra-index-url", "https://pypi.nvidia.com/", "--index-strategy", "unsafe-best-match"]
LOCKS = {
    "vllm_cu13": [],
    "jax_cu12": [],
    "jax_cu13": ["-c", "locks/jax_cu13.constraints"],
    "tensorrt_cu12": NVIDIA,
    "tensorrt_cu13": NVIDIA,
}
COMMON = ["pip", "compile", "--generate-hashes", "--emit-index-url", "--no-header", "--no-annotate", "--python-version", "3.12", "--python-platform", "x86_64-manylinux_2_34",
          "--only-binary", ":all:", "--index-url", "https://pypi.org/simple"]


def header(name, args):
    cmd = "uv " + " ".join(COMMON + args + ["locks/%s.in" % name])
    return ("# STATUS: HASHED, 2026-11-17. Lock of the open ML row flavour `%s` (docs/design/V3_OPEN_ML_ROWS.md): the full transitive closure, `--hash=sha256:` per file as the index publishes it.\n"
            "# Installed with `pip install --require-hashes --only-binary=:all: --no-deps -r <this file>`. Generated by scripts/apps/mlrows/gen_locks.py:\n"
            "#   %s\n" % (name, cmd))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--uv", default="uv")
    ap.add_argument("names", nargs="*")
    a = ap.parse_args(argv)
    for name in a.names or sorted(LOCKS):
        out = HERE / "locks" / (name + ".lock.txt")
        r = subprocess.run([a.uv] + COMMON + LOCKS[name] + [str(HERE / "locks" / (name + ".in"))], capture_output=True, text=True, cwd=str(HERE))
        if r.returncode != 0:
            print(r.stderr[-2000:], file=sys.stderr)
            return 1
        out.write_text(header(name, LOCKS[name]) + r.stdout)
        print("wrote", out.name, len(r.stdout.splitlines()), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
