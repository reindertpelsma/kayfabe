"""Regenerate caselist.tsv from caselist_spec.json and the main mustpass of a checkout of the pinned CTS (a developer tool; a run
never needs it: the committed list is the experiment).

STATUS: LIVE, 2026-11-17.   gen_caselist.py --cts DIR [--write]
DIR must be at the pinned commit (the HEAD is checked; sparse checkouts of external/vulkancts/mustpass/main are enough). Without
--write the list is printed and compared with the committed one (exit 1 if they differ). With --write it replaces caselist.tsv and the
caselist_sha256 field of pins.json."""
import argparse
import collections
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import vkcts_lib as L  # noqa: E402


def read_mustpass(cts, listing):
    names = set()
    for rel in (cts / "external/vulkancts/mustpass/main" / "x").parent.joinpath(listing).read_text().split():
        for line in (cts / "external/vulkancts/mustpass/main" / rel).read_text().splitlines():
            line = line.strip()
            if line:
                names.add(line)
    return sorted(names)


def select(names, bucket):
    """The deterministic stratified pick of one bucket (see `rule` in the spec). Returns a sorted list of distinct names."""
    inc, exc = bucket["include"], bucket.get("exclude", [])
    fil = re.compile(bucket["filter"]) if bucket.get("filter") else None
    exf = re.compile(bucket["exclude_filter"]) if bucket.get("exclude_filter") else None
    strata = collections.OrderedDict()
    for n in names:
        p = next((p for p in inc if n.startswith(p)), None)
        if p is None or any(n.startswith(e) for e in exc) or (fil and not fil.search(n)) or (exf and exf.search(n)):
            continue
        tail = n[len(p):].split(".")
        strata.setdefault(p + ".".join(tail[:bucket["depth"]]), []).append(n)
    keys = sorted(strata)
    count, picked = bucket["count"], []
    if not keys:
        return picked
    if len(keys) >= count:
        per = {keys[int((i + 0.5) * len(keys) / count)]: 1 for i in range(count)}
    else:
        base, extra = divmod(count, len(keys))
        order = sorted(keys, key=lambda k: (-len(strata[k]), k))
        per = {k: base + (1 if order.index(k) < extra else 0) for k in keys}
    for k in sorted(per):
        lst, q = strata[k], min(per[k], len(strata[k]))
        picked += [lst[int((j + 0.5) * len(lst) / q)] for j in range(q)]
    return sorted(set(picked))


def build(cts, spec, pins):
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=cts, capture_output=True, text=True).stdout.strip()
    L.head_matches(head, pins["cts"]["commit"])
    names = read_mustpass(cts, Path(spec["mustpass_list"]).name)
    out, seen = [], set()
    for b in spec["buckets"]:
        for n in select(names, b):
            if n not in seen:
                seen.add(n)
                out.append((b["area"], n))
    for a in spec["required_areas"]:
        if not any(x == a for x, _ in out):
            raise L.CaselistError("area %s selected nothing" % a)
    info = pins["run"]["info_cases"]
    header = ["# Vulkan CTS row case list (area TAB case). Generated by gen_caselist.py from caselist_spec.json and the main mustpass of",
              "# %s (%s). The list is part of the experiment: a change needs the digest in pins.json changed with it." % (pins["cts"]["tag"], pins["cts"]["commit"])]
    return "\n".join(header + ["info\t" + c for c in info] + ["%s\t%s" % e for e in out]) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cts", required=True)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    pins = L.validate_pins(json.loads((HERE / "pins.json").read_text()))
    spec = json.loads((HERE / "caselist_spec.json").read_text())
    text = build(Path(a.cts), spec, pins)
    entries = L.read_caselist(text)
    L.validate_caselist(entries, pins["run"]["info_cases"], spec["required_areas"])
    sha = L.caselist_sha256(text)
    cnt = collections.Counter(x for x, _ in entries)
    print("cases=%d sha256=%s areas=%s" % (len(entries), sha, dict(cnt)))
    path = HERE / "caselist.tsv"
    if a.write:
        path.write_text(text)
        p = (HERE / "pins.json").read_text()
        p = re.sub(r'("caselist_sha256": ")[0-9a-f]*(")', r"\g<1>%s\2" % sha, p)
        (HERE / "pins.json").write_text(p)
        return 0
    same = path.is_file() and path.read_text() == text
    print("committed list %s" % ("is identical" if same else "DIFFERS"))
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
