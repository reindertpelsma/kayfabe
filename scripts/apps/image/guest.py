"""Cloud-init executable: install pinned data, build with argv, report, power off.

Only runs inside the coordinator's guest. Ubuntu/NVIDIA package maintainer
programs and upstream build systems are official installers; no authored shell
script, shell command string or host compiler is used by this path.
"""

import glob
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import traceback
import tarfile
import elf
import scan_image
import input_disk

from common import (
    canonical,
    check_argv,
    extract,
    locked_wheels,
    read_recipe,
    requirements,
    sha256_file,
    validate_inventory,
    verify_file,
)

ROOT = Path("/opt/apps/image")
PORT = Path("/dev/virtio-ports/org.kayfabe.image")


def run(argv, cwd=None, env=None, timeout=7200, capture=False):
    check_argv(argv)
    return subprocess.run(
        argv,
        cwd=cwd,
        env=env,
        check=True,
        timeout=timeout,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
        text=capture,
    )


def copy_outputs(spec):
    source = spec["from"]
    target = Path(spec["to"])
    paths = sorted(glob.glob(source))
    if not paths:
        raise ValueError(f"copy input missing: {source}")
    if spec.get("directory"):
        target.mkdir(parents=True, exist_ok=True)
        for p in paths:
            # Preserve SONAME symlinks; glob includes the backing regular files.
            shutil.copy2(p, target / Path(p).name, follow_symlinks=False)
    else:
        if len(paths) != 1:
            raise ValueError("copy to a file requires exactly one input")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(paths[0], target, follow_symlinks=False)


def fetch_served(pin, url, cache):
    """Slirp-local transport, separate from public HTTPS input acquisition."""
    import urllib.parse
    import urllib.request

    u = urllib.parse.urlsplit(url)
    if (
        u.scheme != "http"
        or u.hostname != "10.0.2.100"
        or u.username
        or u.password
        or u.query
        or u.fragment
    ):
        raise ValueError("guest input transport must be the QEMU host allowlist")
    cache.mkdir(parents=True, exist_ok=True)
    out = cache / pin["sha256"]
    part = out.with_suffix(".part")
    try:
        with urllib.request.urlopen(url, timeout=120) as src, part.open("wb") as dst:
            count = 0
            for block in iter(lambda: src.read(1024 * 1024), b""):
                count += len(block)
                if count > pin["size"]:
                    raise ValueError("oversized served input")
                dst.write(block)
        verify_file(part, pin)
        part.replace(out)
    finally:
        part.unlink(missing_ok=True)
    return out


def pip_files():
    """Hash installed distribution bytes, excluding runtime-generated bytecode and RECORD itself."""
    result = {}
    for dist in importlib.metadata.distributions():
        import re

        name = re.sub(r"[-_.]+", "-", dist.metadata["Name"]).lower()
        rows = []
        for item in dist.files or []:
            path = dist.locate_file(item)
            if "__pycache__" in item.parts or str(item).endswith((".pyc", "/RECORD")):
                continue
            if path.is_file():
                rows.append((str(item), sha256_file(path)))
        if not rows:
            raise ValueError("installed pip distribution has no files")
        result[name] = hashlib.sha256(canonical(sorted(rows))).hexdigest()
    return result


def environment(recipe):
    env = os.environ.copy()
    env.update(recipe["environment"])
    env["DEBIAN_FRONTEND"] = "noninteractive"
    return env


def get_input(pin, session):
    cache = ROOT / "downloads"
    cache.mkdir(parents=True, exist_ok=True)
    p = cache / pin["sha256"]
    if p.exists():
        verify_file(p, pin)
        return p
    if pin["id"] in session.get("official_ids", []):
        if session.get("official_disk") != input_disk.DEVICE:
            raise ValueError("official input requires the declared transient disk")
        try:
            return input_disk.read(input_disk.DEVICE, pin, cache)
        except (ValueError, OSError) as error:
            raise ValueError(
                "MEDIA_DRIFT " + pin["id"] + ": official input disk integrity failure"
            ) from error
    return fetch_served(pin, session["server_url"] + "/" + pin["sha256"], cache)


def link_files(items):
    for item in items:
        p = Path(item["path"])
        p.parent.mkdir(parents=True, exist_ok=True)
        if p.is_symlink():
            if os.readlink(p) != item["target"]:
                raise ValueError("conflicting declared link")
        elif p.exists():
            raise ValueError("link destination exists")
        else:
            p.symlink_to(item["target"])


def install_one_official(pin, recipe, session, builder=False):
    env = environment(recipe)
    p = get_input(pin, session)
    wheelhouse = ROOT / "wheelhouse"
    wheelhouse.mkdir(parents=True, exist_ok=True)
    if pin["kind"] == "run":
        executable = p.with_name(pin["filename"])
        shutil.copyfile(p, executable)
        executable.chmod(0o755)
        argv = [str(executable) if a == "{file}" else a for a in pin["install_argv"]]
        if builder:
            argv.append("--no-kernel-modules")
        run(argv, env=env)
    elif pin["kind"] == "archive":
        extract(p, pin["target"], pin.get("strip_components", 1))
    elif pin["kind"] == "wheel":
        shutil.copyfile(p, wheelhouse / pin["filename"])
    else:
        raise ValueError("unexpected official install kind")
    receipt = ROOT / "official-receipts.json"
    rows = json.loads(receipt.read_text()) if receipt.exists() else {}
    rows[pin["id"]] = sha256_file(p)
    pending = receipt.with_suffix(".tmp")
    pending.write_bytes(canonical(rows))
    pending.replace(receipt)


def install_official(recipe, session, builder=False):
    env = environment(recipe)
    for pin in recipe["official_fetch"]:
        if pin["kind"] == "run" and pin["version"] != recipe["guest"]["nvidia_version"]:
            continue
        if builder and pin["kind"] == "wheel":
            continue
        if pin["kind"] == "run":
            install_one_official(pin, recipe, session, builder)
        else:
            run(pin["install_argv"], env=env)
    for item in recipe["official_write_files"]:
        p = Path(item["path"])
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(item["content"])
        p.chmod(int(item.get("permissions", "0644"), 8))
    links = [
        item
        for item in recipe["official_links"]
        if not builder or not item["path"].startswith("/opt/apps/bundle/")
    ]
    link_files(links)
    run(["ldconfig"], env=env)


def install_wheels(recipe, session, layer):
    env = environment(recipe)
    wheelhouse = ROOT / "wheelhouse"
    wheelhouse.mkdir(parents=True, exist_ok=True)
    selected = {a["package"]: a for a in recipe["artifacts"] if a["kind"] == "wheel"}
    if layer == "runtime":
        selected.update(
            {a["package"]: a for a in recipe["official_fetch"] if a["kind"] == "wheel"}
        )
    for pin in selected.values():
        shutil.copyfile(get_input(pin, session), wheelhouse / pin["filename"])
    if layer == "open":
        run(["/usr/bin/python3", "-m", "venv", "/opt/apps/venv"], env=env)
    lock = ROOT / (
        "requirements-runtime.lock" if layer == "runtime" else "requirements.lock"
    )
    if lock.read_text() != requirements(recipe, layer):
        raise ValueError("guest requirements drift")
    argv = [
        "/opt/apps/venv/bin/python",
        "-m",
        "pip",
        "install",
        "--no-index",
        "--no-cache-dir",
        "--require-hashes",
        "--only-binary=:all:",
        "--find-links",
        str(wheelhouse),
        "-r",
        str(lock),
    ]
    if layer == "runtime":
        argv.extend(["--upgrade", "--force-reinstall"])
    run(argv, env=env)


def source_inputs(recipe, session):
    for pin in recipe["artifacts"]:
        if pin["kind"] == "archive" and pin["id"] != "blender":
            extract(
                get_input(pin, session), pin["target"], pin.get("strip_components", 1)
            )
    for p in [
        "/opt/apps/source/local",
        "/opt/apps/bundle/bin",
        "/opt/apps/bundle/samples",
        "/opt/apps/bundle/llama",
        "/opt/apps/bundle/gpu-burn",
    ]:
        Path(p).mkdir(parents=True, exist_ok=True)


def build_apps(recipe, runtime=False):
    env = environment(recipe)
    shared = {}
    for item in recipe["builds"]:
        is_static = item["requires"] == "nvidia-layer-static"
        if is_static != runtime:
            continue
        cwd = Path(item["cwd"])
        cwd.mkdir(parents=True, exist_ok=True)
        for argv in item["commands"]:
            run(argv, cwd=cwd, env=env)
        for spec in item.get("copies", []):
            copy_outputs(spec)
        for output in item["outputs"]:
            p = Path(output["path"])
            if not p.is_file():
                raise ValueError("missing declared build output: " + str(p))
            if (
                output["sha256"] != "inventory-only"
                and sha256_file(p) != output["sha256"]
            ):
                raise ValueError("built output pin mismatch")
        for path, libraries in item.get("shared_runtime_outputs", {}).items():
            shared[path] = elf.check_shared(path, libraries)
    if not runtime:
        for spec in recipe["copies"]:
            copy_outputs(spec)
        # Preserve upstream OSS notices; never copy the CUDA toolkit's proprietary licences.
        for source in ("cuda-samples", "llama", "clpeak", "gpu-burn", "vkpeak"):
            p = Path("/opt/apps/source") / source / "LICENSE"
            if p.is_file():
                dest = Path("/opt/apps/bundle/share/licenses") / source / "LICENSE"
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(p, dest)
    return shared


def export_apps():
    root = Path("/opt/apps/bundle")
    port = Path("/dev/virtio-ports/org.kayfabe.export")
    with (
        port.open("wb", buffering=0) as output,
        tarfile.open(
            fileobj=output, mode="w|gz", format=tarfile.USTAR_FORMAT
        ) as archive,
    ):
        for p in sorted(root.rglob("*")):
            if p.is_file() or p.is_symlink():
                archive.add(
                    p,
                    arcname=p.relative_to("/").as_posix(),
                    recursive=False,
                    filter=lambda info: info.replace(
                        mtime=0, uid=0, gid=0, uname="", gname=""
                    ),
                )


def assemble(recipe, session):
    for pin in recipe["artifacts"]:
        if pin["kind"] == "file":
            p = Path(pin["target"])
            p.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(get_input(pin, session), p)
        elif pin["id"] == "blender":
            extract(
                get_input(pin, session), pin["target"], pin.get("strip_components", 1)
            )
    export = session["export_pin"]
    extract(get_input(export, session), "/", 0)
    install_wheels(recipe, session, "open")


def select_nvidia_opencl():
    # The open hashcat package may pull POCL to satisfy its ICD dependency.
    # Keep that package installed, but prevent a CPU platform becoming the gate target.
    directory = Path("/etc/OpenCL/vendors")
    nvidia = directory / "nvidia.icd"
    if not nvidia.is_file():
        raise ValueError("NVIDIA OpenCL ICD was not installed")
    for path in sorted(directory.glob("*.icd")):
        if path.name != "nvidia.icd":
            path.rename(path.with_suffix(".icd.disabled"))


def clean_transients():
    for p in [ROOT / "downloads", ROOT / "wheelhouse", Path("/opt/apps/source")]:
        if p.exists():
            shutil.rmtree(p)
    run(["apt-get", "clean"])
    run(["fstrim", "--all"])


def dpkg_rows():
    text = run(
        [
            "dpkg-query",
            "--show",
            "--showformat=${db:Status-Abbrev}\t${binary:Package}\t${Architecture}\t${Version}\n",
        ],
        capture=True,
    ).stdout
    return sorted(row for row in text.splitlines() if row.startswith("ii"))


def collect_inventory(recipe, layer):
    spec = recipe["inventory"] if layer == "open" else recipe["runtime_inventory"]
    dpkg = dpkg_rows()
    freeze = run(
        ["/opt/apps/venv/bin/python", "-m", "pip", "freeze", "--all"], capture=True
    ).stdout
    installed = json.loads(
        run(
            ["/opt/apps/venv/bin/python", str(ROOT / "guest.py"), "--pip-inventory"],
            capture=True,
        ).stdout
    )
    files = {}
    symlinks = {}
    paths = set(Path(p) for p in spec["required_paths"])
    for tree in spec["trees"]:
        if not Path(tree).is_dir():
            raise ValueError("missing inventory tree")
        paths.update(Path(tree).rglob("*"))
    for pattern in spec.get("globs", []):
        found = glob.glob(pattern)
        if not found:
            raise ValueError("empty inventory glob")
        paths.update(map(Path, found))
    for name in spec["dpkg_binaries"]:
        p = shutil.which(name)
        if p is None:
            raise ValueError("missing app: " + name)
        paths.add(Path(p))
    for p in sorted(paths):
        if p.is_symlink():
            symlinks[str(p)] = os.readlink(p)
        if p.is_file():
            files[str(p)] = sha256_file(p)
        elif not p.is_dir():
            raise ValueError("missing inventory file: " + str(p))
    driver = (
        run(["modinfo", "-F", "version", "nvidia"], capture=True).stdout.strip()
        if layer == "runtime"
        else None
    )
    inv = {
        "schema_version": 1,
        "layer": layer,
        "guest": {"kernel": os.uname().release, "nvidia_module_version": driver},
        "dpkg": dpkg,
        "pip_freeze": sorted(freeze.splitlines()),
        "pip_files": installed,
        "wheels": locked_wheels(recipe, layer),
        "files": files,
        "symlinks": symlinks,
    }
    if layer == "runtime":
        inv["official_receipts"] = json.loads(
            (ROOT / "official-receipts.json").read_text()
        )
    if layer == "open":
        scan = scan_image.scan(
            "/", dpkg, notice_policy=recipe["image_policy"]["nvidia_notice_policy"]
        )
        allowed = set(json.loads((ROOT / "allowed_packages.json").read_text()))
        for row in dpkg:
            package = row.split("\t")[1].split(":")[0]
            if package not in allowed:
                scan["findings"].append(
                    {
                        "path": "/var/lib/dpkg/status",
                        "reason": "package outside verified main/universe metadata: "
                        + package,
                    }
                )
        scan["clean"] = not scan["findings"]
        inv["nvidia_scan"] = scan_image.inventory_result(scan)
        inv["no_nvidia_proprietary_files"] = scan["clean"]
    return inv


def main():
    if sys.argv[1:] == ["--pip-inventory"]:
        print(json.dumps(pip_files(), sort_keys=True))
        return
    recipe = read_recipe(ROOT / "recipe.json")
    session = json.loads((ROOT / "session.json").read_text())
    if len(sys.argv) == 3 and sys.argv[1] == "--install-official":
        pin = next(a for a in recipe["official_fetch"] if a["id"] == sys.argv[2])
        install_one_official(pin, recipe, session, session["mode"] == "builder")
        return
    report = {k: session[k] for k in ("nonce", "mode", "recipe_sha256")}
    try:
        if report["recipe_sha256"] != hashlib.sha256(canonical(recipe)).hexdigest():
            raise ValueError("guest recipe digest differs")
        if os.uname().release != recipe["guest"]["kernel"]:
            raise ValueError("guest kernel differs")
        mode = session["mode"]
        if mode in ("builder", "assemble"):
            run(
                [
                    "systemctl",
                    "mask",
                    "--now",
                    "apt-daily.service",
                    "apt-daily.timer",
                    "apt-daily-upgrade.service",
                    "apt-daily-upgrade.timer",
                    "unattended-upgrades.service",
                ]
            )
            run(
                [
                    "apt-mark",
                    "hold",
                    "linux-image-virtual",
                    "linux-headers-virtual",
                    "linux-headers-generic",
                ]
            )
        if mode == "builder":
            install_official(recipe, session, builder=True)
            source_inputs(recipe, session)
            shared = build_apps(recipe)
            export_apps()
            inv = {
                "layer": "builder",
                "shared_runtime": shared,
                "files": {
                    str(p): sha256_file(p)
                    for p in Path("/opt/apps/bundle").rglob("*")
                    if p.is_file()
                },
            }
        else:
            if mode == "assemble":
                assemble(recipe, session)
                clean_transients()
            elif mode == "provision":
                install_official(recipe, session)
                select_nvidia_opencl()
                install_wheels(recipe, session, "runtime")
                source_inputs(recipe, session)
                build_apps(recipe, runtime=True)
                clean_transients()
            elif mode not in ("verify-open", "verify-runtime"):
                raise ValueError("unknown guest mode")
            inv = collect_inventory(
                recipe, "runtime" if mode in ("provision", "verify-runtime") else "open"
            )
        if mode != "builder":
            validate_inventory(inv, recipe)
        report.update(status="complete", inventory=inv)
        with PORT.open("wb", buffering=0) as port:
            port.write(canonical(report) + b"\n")
        with open("/dev/ttyS0", "w") as serial:
            serial.write(
                f"\nKF_APPS_IMAGE_COMPLETE {session['nonce']} {hashlib.sha256(canonical(inv)).hexdigest()}\n"
            )
            serial.flush()
    except Exception as error:
        report.update(status="error", error=type(error).__name__ + ": " + str(error))
        # Preserve all scan findings in the failure report, never manufacture a clean manifest.
        if "inv" in locals():
            report["inventory"] = inv
        with PORT.open("wb", buffering=0) as port:
            port.write(canonical(report) + b"\n")
        traceback.print_exc()
    finally:
        Path("/var/lib/cloud/scripts/per-instance/kayfabe-apps-image").unlink(
            missing_ok=True
        )
        run(["systemctl", "poweroff"], timeout=60)


if __name__ == "__main__":
    main()
