#!/usr/bin/env python3
"""Render historical measured cells separately from current beta acceptance."""
import csv
from pathlib import Path

root=Path(__file__).resolve().parents[2]
rows=list(csv.DictReader((root/'docs/support_evidence.tsv').open(),delimiter='\t'))
for row in rows:row['status']='UNTESTED' if row['revision']=='C6' else 'STALE'
with (root/'docs/SUPPORT_MATRIX.tsv').open('w') as output:
    writer=csv.DictWriter(output,fieldnames=list(rows[0]),delimiter='\t',lineterminator='\n')
    writer.writeheader();writer.writerows(rows)
text='''# Support evidence matrix

STATUS: BETA CANDIDATE / NO EXTERNAL SUPPORT PATH, 2026-10-20.

CODE READ: generated by scripts/release/render_support.py from support_evidence.tsv.
STALE means a different product revision, not current certification. UNKNOWN is
not filled from a neighboring run. All C6 hardware cells remain UNTESTED.
The source rootless report is on the public branch claude/rootless-audit-20261016
at 32d7319b2; its product binary was 0a746117. Its host was Ubuntu 26.04,
kernel 7.0.0-34, stock open NVIDIA 595.91.07. ABI admission alone is not support.

| Family / die | Host driver | Guest OS | Guest driver | Product revision | Status | Measured scope / limit |
|---|---|---|---|---|---|---|
'''
for row in rows:
    text+='| '+row['family']+' / '+row['die']+' | '+' | '.join(row[key] for key in ['host_driver','guest_os','guest_driver','revision','status','result'])+' |\n'
text+='''
CODE READ source: [rootless audit](https://github.com/reindertpelsma/kayfabe/blob/32d7319b2/traces/rootless_audit_20261016/REPORT.txt).
The captured-caps replacement has separate exact-die/branch measurement rows;
those word measurements do not establish a supported Windows boot/workload cell.
'''
(root/'docs/SUPPORT_MATRIX.md').write_text(text)
