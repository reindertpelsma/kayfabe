"""Build an Unreal installed build from a source tree the user supplies, and package it as a cache artifact (stdlib only).

STATUS: DESIGN-ONLY tooling, 2026-11-17. GPU-free unit tests with a fake runner (scripts/ci/test_unreal_build.py); NOTHING here was
run against a real source tree: no Setup.sh, no download, no build, no upload. Design: docs/design/V3_UNREAL_IMAGE.md.

This is a trusted-machine tool. Rented (untrusted) boxes never run `build` or `package`; they fetch a finished artifact.

    build_installed.py plan     --source DIR [--clone] [--package]       key, phases, disk and time estimates; runs nothing
    build_installed.py key      --source DIR [--source-id ID] [--allow-dirty]
    build_installed.py build    --source DIR --work DIR --allow-modify-source [--package] [--cache-out DIR] [--jobs N]
                                [--reclaim] [--restart] [--clone REPO [--ref REF]] [--source-id ID] [--allow-dirty]
    build_installed.py verify   ARTIFACT [--manifest FILE] [--source DIR] [--expect-sha256 H]
    build_installed.py pin      --manifest FILE [--prefix P]             the deployment-config entry and the download manifest
    build_installed.py upload   --manifest FILE --artifact FILE --endpoint URL --bucket B [--prefix P] [--execute]
    build_installed.py resolve  [--mode standalone|strict|worker] [--unreal-artifact P|URL] [--unreal-manifest M]
                                [--unreal-source DIR | --unreal-source-clone [REPO]] [--unreal-cache-out DIR]
                                [--cache-listing FILE] [--expect-sha256 H] ...

What the build needs from the network (so that nobody is surprised): `Setup.sh` downloads the source's dependency set and the
bundled Linux toolchain from Epic's content delivery hosts (named inside the source tree's own scripts and manifests). `--clone`
uses the user's own `gh` login. Nothing else in this tool opens a socket.

Resume: each phase is marked in WORK/state.json for one cache key; a second `build` skips finished phases. Inside the BuildGraph
phase the compiler's own incremental build applies (UNVERIFIED that an interrupted BuildGraph run resumes cheaply).
"""

import argparse
import json
import os
import shutil
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import resolve_unreal as RS  # noqa: E402
import ue_lib as L  # noqa: E402

TIMEOUTS = {"clone": 4 * 3600, "setup": 4 * 3600, "genproj": 1800, "buildgraph": 16 * 3600, "package": 4 * 3600}  # seconds
DEFAULT_CLONE_REPO = "EpicGames/UnrealEngine"


def sysinfo():
    """CPUs and RAM in GB of this machine (Linux)."""
    cpus = os.cpu_count() or 1
    ram = 0.0
    try:
        with open("/proc/meminfo") as f:
            for line in f:
                if line.startswith("MemTotal:"):
                    ram = int(line.split()[1]) / 1048576.0
                    break
    except OSError:
        pass
    return cpus, ram


def safe_child(root, rel):
    """root/rel only if it stays inside root and no component is a symlink (used by --reclaim)."""
    p = os.path.join(root, rel)
    real_root = os.path.realpath(root)
    if os.path.realpath(p) != os.path.join(real_root, rel) or os.path.islink(p):
        raise L.UnrealError(L.FAIL_PATH, "refusing to touch %s: not a plain path inside the source" % rel)
    return p


RECLAIM = ("Engine/Intermediate/Build", "LocalBuilds/InstalledDDC")  # generated by the build, rebuildable


class Builder:
    def __init__(self, runner, source, work, environ=None, free_fn=L.free_bytes, sysinfo_fn=sysinfo, dev_of=None, say=print):
        self.runner, self.source, self.work = runner, os.path.abspath(source), os.path.abspath(work)
        self.environ = os.environ if environ is None else environ
        self.free_fn, self.sysinfo_fn, self.dev_of, self.say = free_fn, sysinfo_fn, dev_of, say

    # -------------------------------------------------------------------------------------------------------- helpers
    def locations(self, out=None):
        return L.location_paths(self.source, os.path.join(self.work, "installed"), out or os.path.join(self.work, "out"))

    def log(self, phase):
        return os.path.join(self.work, "logs", phase + ".log")

    def step(self, phase, argv, cwd, clone=False):
        env = L.build_env(self.environ, clone=clone)
        self.say("KF_UNREAL_PHASE_START phase=%s argv0=%s" % (phase, os.path.basename(argv[0])))
        t0 = time.time()
        rc = self.runner.run(argv, cwd, env, self.log(phase), TIMEOUTS[phase])
        self.say("KF_UNREAL_PHASE_END phase=%s rc=%d secs=%d log=%s" % (phase, rc, time.time() - t0, self.log(phase)))
        return rc

    def preflight(self, phases, out):
        cpus, ram = self.sysinfo_fn()
        L.check_ram(ram)
        for tool in ("git", "tar") + (("zstd",) if "package" in phases else ()):
            if shutil.which(tool, path=self.environ.get("PATH")) is None and not getattr(self.runner, "fake", False):
                raise L.UnrealError(L.FAIL_PREREQ, "%s is not installed" % tool)
        # Setup.sh runs `sudo apt-get install build-essential` itself when a Debian-family system lacks it; that would prompt for a
        # password. Refuse here instead, and say what to install.
        if os.path.exists("/etc/os-release") and shutil.which("dpkg-query", path=self.environ.get("PATH")) and not getattr(self.runner, "fake", False):
            rc, _ = self.runner.capture(["dpkg-query", "-W", "-f=${Status}", "build-essential"], env=L.build_env(self.environ))
            if rc != 0:
                raise L.UnrealError(L.FAIL_PREREQ, "build-essential is not installed (Setup.sh would try sudo); install it first")
        for loc in (self.work,):
            os.makedirs(loc, exist_ok=True)
        os.makedirs(os.path.join(self.work, "logs"), exist_ok=True)
        return cpus, ram

    # ----------------------------------------------------------------------------------------------------------- build
    def build(self, allow_modify_source, package=False, cache_out=None, jobs=None, reclaim=False, restart=False,
              clone=None, ref="release", source_id=None, allow_dirty=False, kayfabe_rev="unknown"):
        if not allow_modify_source:
            raise L.UnrealError(L.FAIL_MODIFY, "the build writes into the source tree (git hooks, dependencies, intermediates): pass --allow-modify-source, or give it a copy")
        phases = L.phases_for(bool(clone), package or bool(cache_out))
        out = cache_out or os.path.join(self.work, "out")
        cpus, ram = self.preflight(phases, out)
        self.say("KF_UNREAL_PLAN\n" + L.plan_text(phases))
        statefile = os.path.join(self.work, "state.json")
        if restart and os.path.exists(statefile):
            os.remove(statefile)
        # the key needs the source: a clone phase (if any) runs before it is computed
        state = None
        if clone:
            L.check_disk("clone", self.locations(out), free_fn=self.free_fn, dev_of=self.dev_of)
            if not os.path.isdir(self.source) or not os.listdir(self.source):
                if self.step("clone", ["gh", "repo", "clone", clone, self.source, "--", "--depth", "1", "--branch", ref], self.work, clone=True) != 0:
                    raise L.UnrealError(L.FAIL_CLONE, "gh repo clone failed; see %s" % self.log("clone"))
        comp = L.compute_key(self.runner, self.source, allow_dirty, source_id)
        state = L.State(statefile, comp["key"])
        if clone:
            state.mark("clone", 0)
        self.say("KF_UNREAL_KEY key=%s version=%s" % (comp["key"], comp["version"]))
        argv_by_phase = {
            "setup": (list(L.RECIPE["setup"]), self.source),
            "genproj": (list(L.RECIPE["genproj"]), self.source),
        }
        installed = self.locations(out)["installed"]
        n_jobs = L.compute_jobs(cpus, ram, jobs)
        argv_by_phase["buildgraph"] = (L.buildgraph_argv(self.source, installed, comp["key"], n_jobs), self.source)
        for phase in phases:
            if phase in ("clone", "package"):
                continue
            if state.done(phase):
                self.say("KF_UNREAL_PHASE_SKIP phase=%s (done for this key)" % phase)
                continue
            L.check_disk(phase, self.locations(out), free_fn=self.free_fn, dev_of=self.dev_of)
            argv, cwd = argv_by_phase[phase]
            t0 = time.time()
            rc = self.step(phase, argv, cwd)
            state.mark(phase, rc, int(time.time() - t0))
            if rc != 0:
                raise L.UnrealError(L.FAIL_BUILD, "phase %s exited %d; see %s" % (phase, rc, self.log(phase)))
        tree = L.installed_tree_dir(installed)
        problems, warnings = L.verify_tree(tree)
        for w in warnings:
            self.say("KF_UNREAL_WARN missing_expected=%s" % w)
        if problems:
            raise L.UnrealError(L.FAIL_TREE, "installed tree lacks %s" % ", ".join(problems))
        self.say("KF_UNREAL_TREE tree=%s" % tree)
        result = {"key": comp["key"], "tree": tree, "manifest": None, "artifact": None}
        if package or cache_out:
            result.update(self.package(comp, tree, out, state, kayfabe_rev))
        if reclaim:
            for rel in RECLAIM:
                p = safe_child(self.source, rel)
                if os.path.isdir(p):
                    shutil.rmtree(p)
                    self.say("KF_UNREAL_RECLAIM removed=%s" % rel)
        return result

    # --------------------------------------------------------------------------------------------------------- package
    def package(self, comp, tree, out, state, kayfabe_rev):
        L.check_disk("package", self.locations(out), free_fn=self.free_fn, dev_of=self.dev_of)
        os.makedirs(out, exist_ok=True)
        name = "artifact.tar.zst"
        path = os.path.join(out, name)
        part = path + ".partial"
        tar, zstd = L.tar_zstd_argv(tree, L.RECIPE["archive"]["level"])
        rc = self.runner.pipeline(tar, zstd + ["-o", part, "-f"], self.log("package"), TIMEOUTS["package"], L.build_env(self.environ))
        if rc != 0:
            raise L.UnrealError(L.FAIL_BUILD, "packaging failed (rc %d); see %s" % (rc, self.log("package")))
        os.replace(part, path)
        sha, size = L.sha256_file(path)
        stats = L.tree_stats(tree)
        libs = self.audit_libs(tree)
        cpus, ram = self.sysinfo_fn()
        man = L.make_manifest(comp, {"name": name, "sha256": sha, "size": size}, stats, self.observe_clang(tree), libs,
                              {"cpus": cpus, "ram_gb": round(ram, 1)}, kayfabe_rev)
        L.validate_manifest(man)
        mpath = os.path.join(out, "manifest.json")
        with open(mpath + ".tmp", "w") as f:
            json.dump(man, f, sort_keys=True, indent=1)
        os.replace(mpath + ".tmp", mpath)
        state.mark("package", 0)
        self.say("KF_UNREAL_ARTIFACT path=%s size=%d sha256=%s manifest=%s" % (path, size, sha, mpath))
        return {"artifact": path, "manifest": mpath, "sha256": sha, "size": size}

    def observe_clang(self, tree):
        """The bundled compiler the build used, as an observation (never part of the key)."""
        base = os.path.join(tree, "Engine/Extras/ThirdPartyNotUE/SDKs/HostLinux/Linux_x64")
        try:
            versions = sorted(os.listdir(base))
        except OSError:
            return None
        return versions[-1][:120] if versions else None

    def audit_libs(self, tree):
        """sonames the installed binaries need from the SYSTEM (ldd says `not found` when the machine lacks them; run on the
        machine that built, so the list is what a clean guest must provide). Empty when ldd is unavailable."""
        if getattr(self.runner, "fake", False) and not hasattr(self.runner, "ldd_text"):
            return []
        text = []
        bindir = os.path.join(tree, "Engine/Binaries/Linux")
        env = L.build_env(self.environ)
        env["LD_LIBRARY_PATH"] = bindir
        try:
            names = sorted(n for n in os.listdir(bindir) if os.access(os.path.join(bindir, n), os.X_OK) or n.endswith(".so"))
        except OSError:
            return []
        for n in names[:400]:
            rc, out = self.runner.capture(["ldd", os.path.join(bindir, n)], env=env, timeout=60)
            if rc == 0:
                text.append(out.decode("utf-8", "replace"))
        return L.parse_ldd_missing("\n".join(text))


# ---------------------------------------------------------------------------------------------------- the real runner
class RealRunner(L.Runner):
    def pipeline(self, argv1, argv2, log_path, timeout, env):
        import subprocess

        with open(log_path, "ab") as log:
            log.write(("KF_UNREAL_START %s pipeline=%s|%s\n" % (L.utc_now(), os.path.basename(argv1[0]), os.path.basename(argv2[0]))).encode())
            log.flush()
            p1 = subprocess.Popen(argv1, stdout=subprocess.PIPE, stderr=log, env=env, stdin=subprocess.DEVNULL)
            p2 = subprocess.Popen(argv2, stdin=p1.stdout, stdout=log, stderr=log, env=env)
            p1.stdout.close()
            try:
                rc2 = p2.wait(timeout=timeout)
                rc1 = p1.wait(timeout=60)
            except subprocess.TimeoutExpired:
                p1.kill()
                p2.kill()
                rc1 = rc2 = 124
            rc = rc1 or rc2
            log.write(("KF_UNREAL_EXIT rc=%d\n" % rc).encode())
            return rc


class RealFacts(RS.Facts):
    def gh_access(self, repo):
        """`gh auth status` then one repository read through the user's own login. Never prompts, never prints a token."""
        import re

        if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo or ""):
            return False, "bad_repository_name"
        if shutil.which("gh") is None:
            return False, "gh_not_installed"
        env = L.build_env(os.environ, clone=True)
        r = L.Runner()
        rc, _ = r.capture(["gh", "auth", "status"], env=env, timeout=30)
        if rc != 0:
            return False, "gh_not_logged_in"
        rc, _ = r.capture(["gh", "api", "repos/" + repo, "--silent"], env=env, timeout=30)
        if rc != 0:
            return False, "no_repo_access"
        return True, ""


# ---------------------------------------------------------------------------------------------------- CLI
def cmd_plan(a):
    phases = L.phases_for(a.clone, a.package)
    print(L.plan_text(phases))
    cpus, ram = sysinfo()
    print("this machine: %d CPUs, %.0f GB RAM, jobs would be %d (RAM minimum %d GB)" % (cpus, ram, L.compute_jobs(cpus, ram), L.MIN_RAM_GB))
    if a.source:
        comp = L.compute_key(L.Runner(), a.source, a.allow_dirty, a.source_id)
        print("key %s version %s recipe %s" % (comp["key"], comp["version"], L.recipe_rev()))
    return 0


def cmd_key(a):
    comp = L.compute_key(L.Runner(), a.source, a.allow_dirty, a.source_id)
    print(json.dumps({"key": comp["key"], "version": comp["version"], "inputs": comp["inputs"]}, sort_keys=True, indent=1))
    return 0


def cmd_build(a):
    b = Builder(RealRunner(), a.source, a.work)
    res = b.build(a.allow_modify_source, a.package, a.cache_out, a.jobs, a.reclaim, a.restart, a.clone, a.ref, a.source_id, a.allow_dirty, kayfabe_rev=rev())
    print(json.dumps(res, sort_keys=True))
    return 0


def rev():
    try:
        rc, out = L.Runner().capture(["git", "-C", os.path.dirname(os.path.abspath(__file__)), "rev-parse", "--short=12", "HEAD"])
        return out.decode().strip() if rc == 0 else "unknown"
    except Exception:
        return "unknown"


def cmd_verify(a):
    d = RS.decide(RS.Opts(mode="standalone", artifact=a.artifact, manifest=a.manifest, source=a.source, expect_sha256=a.expect_sha256, source_id=a.source_id), RealFacts())
    print(json.dumps(d.as_dict(), sort_keys=True))
    print(d.line())
    return d.exit_code


def cmd_pin(a):
    man = L.load_manifest(a.manifest)
    pin = L.pin_entry(man, a.prefix)
    doc = {"schema": L.PIN_SCHEMA, "objects": [pin, L.manifest_pin_entry(man, a.manifest, a.prefix)], "download_manifest": L.download_manifest(pin),
           "note": "deployment data: put it in YOUR config; strict and worker runs enforce size and sha256, standalone runs only record them"}
    print(json.dumps(doc, sort_keys=True, indent=1))
    return 0


def cmd_upload(a):
    man = L.load_manifest(a.manifest)
    L.check_member(a.artifact, man)  # never upload what does not match its own manifest
    pin = L.pin_entry(man, a.prefix)
    files = [(a.artifact, pin["object"]), (a.manifest, L.object_name(man["engine"]["version"], man["key"], a.prefix, "manifest.json"))]
    plans = L.s3_upload_plan(a.endpoint, a.bucket, files)
    for p in plans:
        print(" ".join(p))
    if not a.execute:
        print("(printed only; add --execute to run them. Credentials come from AWS_ACCESS_KEY_ID and AWS_SECRET_ACCESS_KEY in the environment.)")
        return 0
    r = L.Runner()
    env = {k: os.environ[k] for k in ("PATH", "HOME", "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN", "AWS_DEFAULT_REGION", "AWS_REGION") if k in os.environ}
    for p in plans:
        rc, _ = r.capture(p, env=env, timeout=4 * 3600)
        if rc != 0:
            print("KF_UNREAL_UPLOAD_FAILED rc=%d" % rc)
            return 3
    print("KF_UNREAL_UPLOADED objects=%d; now fetch it back through your own presigned URL and run `verify`" % len(plans))
    return 0


def cmd_resolve(a):
    listing = None
    if a.cache_listing:
        with open(a.cache_listing) as f:
            listing = json.load(f)
    clone = a.unreal_source_clone
    if clone == "":
        clone = DEFAULT_CLONE_REPO
    o = RS.Opts(a.mode, a.unreal_artifact, a.unreal_manifest, a.unreal_source, clone, a.unreal_ref, listing, a.expect_sha256, a.unreal_cache_out, a.source_id, a.allow_dirty)
    d = RS.decide(o, RealFacts())
    print(json.dumps(d.as_dict(), sort_keys=True))
    print(d.line())
    if d.extra.get("plan"):
        print(d.extra["plan"])
    return d.exit_code


def parser():
    p = argparse.ArgumentParser(prog="build_installed.py", description=__doc__.split("\n\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)

    def common(s):
        s.add_argument("--source-id", default=None)
        s.add_argument("--allow-dirty", action="store_true")

    s = sub.add_parser("plan"); s.add_argument("--source"); s.add_argument("--clone", action="store_true"); s.add_argument("--package", action="store_true"); common(s); s.set_defaults(f=cmd_plan)
    s = sub.add_parser("key"); s.add_argument("--source", required=True); common(s); s.set_defaults(f=cmd_key)
    s = sub.add_parser("build"); s.add_argument("--source", required=True); s.add_argument("--work", required=True)
    s.add_argument("--allow-modify-source", action="store_true"); s.add_argument("--package", action="store_true"); s.add_argument("--cache-out")
    s.add_argument("--jobs", type=int); s.add_argument("--reclaim", action="store_true"); s.add_argument("--restart", action="store_true")
    s.add_argument("--clone", metavar="REPO"); s.add_argument("--ref", default="release"); common(s); s.set_defaults(f=cmd_build)
    s = sub.add_parser("verify"); s.add_argument("artifact"); s.add_argument("--manifest"); s.add_argument("--source"); s.add_argument("--expect-sha256"); common(s); s.set_defaults(f=cmd_verify)
    s = sub.add_parser("pin"); s.add_argument("--manifest", required=True); s.add_argument("--prefix", default="linux-proprietary"); s.set_defaults(f=cmd_pin)
    s = sub.add_parser("upload"); s.add_argument("--manifest", required=True); s.add_argument("--artifact", required=True)
    s.add_argument("--endpoint", required=True); s.add_argument("--bucket", required=True); s.add_argument("--prefix", default="linux-proprietary"); s.add_argument("--execute", action="store_true"); s.set_defaults(f=cmd_upload)
    s = sub.add_parser("resolve"); s.add_argument("--mode", default="standalone", choices=L.MODES)
    s.add_argument("--unreal-artifact"); s.add_argument("--unreal-manifest"); s.add_argument("--unreal-source"); s.add_argument("--unreal-source-clone", nargs="?", const="")
    s.add_argument("--unreal-ref", default="release"); s.add_argument("--unreal-cache-out"); s.add_argument("--cache-listing"); s.add_argument("--expect-sha256"); common(s); s.set_defaults(f=cmd_resolve)
    return p


def main(argv=None):
    a = parser().parse_args(argv)
    try:
        return a.f(a)
    except L.UnrealError as e:
        print("KF_UNREAL_REFUSED class=%s detail=%s" % (e.cls, e.detail), file=sys.stderr)
        return 3


if __name__ == "__main__":
    sys.exit(main())
