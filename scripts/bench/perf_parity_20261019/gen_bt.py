"""gen_bt.py QEMU_BIN QPID [profile] -> bpftrace program on stdout.
One monotonic clock (bpftrace nsecs = CLOCK_MONOTONIC-ish ktime_get_ns) for kernel tracepoints and uprobes.
profile: tp   = kernel tracepoints only (kvm exits/irq injection, scheduler wake-ups of kf3 threads, syscalls of kf3 workers)
         up   = tp + uprobes/uretprobes on the existing relay symbols (address-based; the binary is non-PIE)
Symbols are resolved with `nm` on QEMU_BIN (mangled names matched by suffix), never hard-coded addresses."""
import subprocess, sys, re
binp, qpid = sys.argv[1], sys.argv[2]
prof = sys.argv[3] if len(sys.argv) > 3 else "up"
HOT = prof in ("tp", "up2", "sys", "lock", "pub", "mk", "irq", "hostpath", "gpuprog")   # light sets: leave out the very hot symbols (Relay::step, user_ring_record, turn_body), the raw syscall stream, apic/eoi, sched_switch
nm = subprocess.run(["nm", "--defined-only", binp], capture_output=True, text=True, check=True).stdout.splitlines()
def find(sfx):
    r = [l.split() for l in nm if l.rstrip().endswith(sfx)]
    r = [x for x in r if len(x) == 3 and x[1] in "tT"]
    assert len(r) == 1, (sfx, r)
    return "0x" + r[0][0].lstrip("0")
# (label, mangled suffix)  -- suffixes are unique tails of the v0-mangled names
PROBES = [
 ("bar0_write",      "6Device10bar0_write"),
 ("latch_deliver",   "6Device17latch_and_deliver"),
 ("serve",           "9ChanPlane5serve"),
 ("user_ring_record","9ChanPlane16user_ring_record"),
 ("turn",            "8userpumpNtB5_4Pump4turn"),
 ("turn_body",       "Pump9turn_body"),
 ("step",            "5Relay4stepNtNtNtCs60hx6PEF3xU_7kf_qemu4chan8userpump6PumpIoEB10_"),
 ("gp_put",          "2Io6gp_put"),
 ("read_pb",         "2Io7read_pb"),
 ("pub_entry",       "2Io13publish_entry"),
 ("pub_marker",      "2Io14publish_marker"),
 ("pub_gate",        "2Io12publish_gate"),
 ("stage",           "2Io5stage"),
 ("event",           "2Io5event"),
 ("wr_guest_get",    "2Io15write_guest_get"),
]
out = []
w = out.append
w("// generated by gen_bt.py profile=%s qpid=%s" % (prof, qpid))
w('BEGIN { printf("# start %llu\\n", nsecs); }')
Q = "/pid == %s/" % qpid
w('tracepoint:kvm:kvm_mmio %s { printf("M %%llu %%d %%d %%llx %%llx\\n", nsecs, tid, args->type, args->gpa, args->val); }' % Q)
w('tracepoint:kvm:kvm_set_irq %s { printf("I %%llu %%d gsi=%%d lvl=%%d\\n", nsecs, tid, args->gsi, args->level); }' % Q)
w('tracepoint:kvm:kvm_apic_accept_irq /pid == %s && (comm == "kf3-worker0" || comm == "kf3-worker1" || comm == "kf3-drainer" || comm == "kf3-display")/ { printf("A %%llu %%d vec=%%d apic=%%d\\n", nsecs, tid, args->vec, args->apicid); }' % qpid)
w('tracepoint:kvm:kvm_inj_virq %s { printf("V %%llu %%d vec=%%d\\n", nsecs, tid, args->vector); }' % Q)
if not HOT: w('tracepoint:kvm:kvm_eoi %s { printf("E %%llu %%d vec=%%d\\n", nsecs, tid, args->vector); }' % Q)
# scheduler: wake-ups and switches of the kf3 threads of this process
w('tracepoint:sched:sched_wakeup /str(args->comm) == "kf3-worker0" || str(args->comm) == "kf3-worker1" || str(args->comm) == "kf3-drainer" || str(args->comm) == "kf3-vamgr" || str(args->comm) == "kf3-chan-act"/ { printf("W %llu %d %s tid=%d tcpu=%d\\n", nsecs, tid, args->comm, args->pid, args->target_cpu); }')
if not HOT: w('tracepoint:sched:sched_switch /str(args->prev_comm) == "kf3-worker0" || str(args->prev_comm) == "kf3-worker1" || str(args->next_comm) == "kf3-worker0" || str(args->next_comm) == "kf3-worker1"/ { printf("S %llu cpu=%d prev=%s/%d st=%d next=%s/%d\\n", nsecs, cpu, args->prev_comm, args->prev_pid, args->prev_state, args->next_comm, args->next_pid); }')
if not HOT: w('tracepoint:raw_syscalls:sys_enter /pid == %s && (comm == "kf3-worker0" || comm == "kf3-worker1")/ { printf("Y %%llu %%d %%s nr=%%d a0=%%lld a1=%%llx\\n", nsecs, tid, comm, args->id, args->args[0], args->args[1]); }' % qpid)
if not HOT: w('tracepoint:raw_syscalls:sys_exit /pid == %s && (comm == "kf3-worker0" || comm == "kf3-worker1")/ { printf("y %%llu %%d %%s nr=%%d ret=%%lld\\n", nsecs, tid, comm, args->id, args->ret); }' % qpid)
if HOT and prof not in ("sys", "lock", "pub") or prof in ("pub", "mk", "irq", "hostpath", "gpuprog"):   # only the eventfd writes of the kf3 workers (irqfd signal to the guest, worker doorbell eventfd): fd and byte count
    w('tracepoint:syscalls:sys_enter_write /pid == %s && (comm == "kf3-worker0" || comm == "kf3-worker1" || comm == "kf3-drainer")/ { printf("Z %%llu %%d %%s fd=%%d n=%%d\\n", nsecs, tid, comm, args->fd, args->count); }' % qpid)
if prof == "sys":   # light set + every syscall of the two workers (enter with args, exit with return value)
    w('tracepoint:raw_syscalls:sys_enter /pid == %s && (comm == "kf3-worker0" || comm == "kf3-worker1")/ { printf("Y %%llu %%d %%s nr=%%d a0=%%llx a1=%%llx a2=%%llx\\n", nsecs, tid, comm, args->id, args->args[0], args->args[1], args->args[2]); }' % qpid)
    w('tracepoint:raw_syscalls:sys_exit /pid == %s && (comm == "kf3-worker0" || comm == "kf3-worker1")/ { printf("y %%llu %%d %%s nr=%%d ret=%%lld\\n", nsecs, tid, comm, args->id, args->ret); }' % qpid)
if prof == "pub":   # light set + ENTRY-ONLY uprobes (one probe hit per call) on the publish path: least perturbation that still timestamps the relay
    for lab, sfx in [("pub_entry", "2Io13publish_entry"), ("pub_marker", "2Io14publish_marker"), ("wr_guest_get", "2Io15write_guest_get"), ("serve", "9ChanPlane5serve")]:
        a = find(sfx)
        w('uprobe:%s:%s %s { printf("U %%llu %%d %s E\\n", nsecs, tid); }' % (binp, a, Q, lab))
if prof in ("irq", "hostpath"):   # light set + the HOST side of the completion path: GPU interrupt handlers (nvidia), their softirq/kthread wake-ups, and every host IRQ entry on any CPU
    w('tracepoint:irq:irq_handler_entry { printf("Q %llu cpu=%d irq=%d %s\\n", nsecs, cpu, args->irq, str(args->name)); }')
    w('tracepoint:irq:irq_handler_exit { printf("q %llu cpu=%d irq=%d\\n", nsecs, cpu, args->irq); }')
    w('tracepoint:sched:sched_wakeup /strncmp(args->comm, "nvidia", 6) == 0 || strncmp(args->comm, "nv_", 3) == 0 || strncmp(args->comm, "irq/", 4) == 0/ { printf("N %llu cpu=%d by=%d %s tid=%d\\n", nsecs, cpu, tid, args->comm, args->pid); }')
    w('tracepoint:sched:sched_switch /strncmp(args->next_comm, "nvidia", 6) == 0 || strncmp(args->next_comm, "irq/", 4) == 0/ { printf("n %llu cpu=%d next=%s tid=%d\\n", nsecs, cpu, args->next_comm, args->next_pid); }')
if prof == "gpuprog":   # light set + the relay's OWN reads of the private channel's USERD words (GP_GET, tagged REFERENCE), logged when the value CHANGES:
    # GPU-side progress of each private channel at the worker's peek cadence (about 8 us). Perturbs the peek loop (one uretprobe per read): ordering is trustworthy, absolute times +20%.
    for lab, sfx in [("get", "CpuViewE7gpu_get"), ("ref", "CpuViewE13gpu_reference")]:
        ad = find(sfx)
        w('uprobe:%s:%s %s { @s[tid] = arg0; @o[tid] = arg1; }' % (binp, ad, Q))
        w('uretprobe:%s:%s %s { $v = *(uint32*)(@s[tid] + 8); if (@last_%s[@o[tid]] != $v) { @last_%s[@o[tid]] = $v; printf("G %%llu %%d %%lx %s %%x\\n", nsecs, tid, @o[tid], $v); } }' % (binp, ad, Q, lab, lab, lab))
if prof in ("mk", "hostpath"):    # light set + entry-only uprobes on the 3 per-submit batch markers and the guest GP_GET write-back (about 10 hits per submit: the least-perturbing relay timestamps)
    for lab, sfx in [("pub_marker", "2Io14publish_marker"), ("wr_guest_get", "2Io15write_guest_get")]:
        a = find(sfx)
        w('uprobe:%s:%s %s { printf("U %%llu %%d %s E\\n", nsecs, tid); }' % (binp, a, Q, lab))
if prof == "lock":   # light set + the two workers' mutex path: the loop's look, the record lookup, serve, and std's contended-lock / wake
    for lab, sfx in [("peek", "6worker9RelayLoop4peek"), ("waiting", "6worker9RelayLoop7waiting"), ("user_ring_record", "9ChanPlane16user_ring_record"), ("serve", "9ChanPlane5serve")]:
        a = find(sfx)
        w('uprobe:%s:%s %s { printf("U %%llu %%d %s E\\n", nsecs, tid); }' % (binp, a, Q, lab))
        w('uretprobe:%s:%s %s { printf("U %%llu %%d %s R\\n", nsecs, tid); }' % (binp, a, Q, lab))
    a = find("5futexNtB2_5Mutex14lock_contended")
    w('uprobe:%s:%s %s { printf("C %%llu %%d E ret=%%llx\\n", nsecs, tid, *(uint64*)reg("sp")); }' % (binp, a, Q))
    w('uretprobe:%s:%s %s { printf("C %%llu %%d R\\n", nsecs, tid); }' % (binp, a, Q))
    a = find("5futexNtB2_5Mutex4wake")
    w('uprobe:%s:%s %s { printf("C %%llu %%d K ret=%%llx\\n", nsecs, tid, *(uint64*)reg("sp")); }' % (binp, a, Q))
if prof in ("up", "up2"):
    for lab, sfx in PROBES:
        if HOT and lab in ("step", "user_ring_record", "turn_body"): continue
        a = find(sfx)
        w('uprobe:%s:%s %s { printf("U %%llu %%d %s E\\n", nsecs, tid); }' % (binp, a, Q, lab))
        w('uretprobe:%s:%s %s { printf("U %%llu %%d %s R\\n", nsecs, tid); }' % (binp, a, Q, lab))
w('END { printf("# end %llu\\n", nsecs); }')
print("\n".join(out))
