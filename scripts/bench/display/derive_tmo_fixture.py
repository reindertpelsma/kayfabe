#!/usr/bin/env python3
"""Derive hardware-oracle program constants from pinned OGKM source, never a die capture.

Usage: derive_tmo_fixture.py <OGKM root> <output.inc>
"""
import hashlib
from pathlib import Path
import re
import sys

root, output = map(Path, sys.argv[1:])
source = root / 'src/nvidia-modeset/src/nvkms-evo3.c'
text = source.read_text()
lines = ['// Generated by scripts/bench/display/derive_tmo_fixture.py; do not edit.',
         '// OGKM nvkms-evo3.c SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest()]
for name in ('OetfPQ512SegSizesLog2', 'OetfPQ512Entries', 'EotfPQ512SegSizesLog2', 'EotfPQ512Entries'):
    matches = re.findall(r'static const NvU(?:16|32) ' + name + r'\[\] = \{(.*?)\};', text, re.S)
    if len(matches) != 1:
        raise ValueError('Missing/ambiguous source array: ' + name)
    values = [int(v.strip(), 0) for v in matches[0].split(',') if v.strip()]
    if not values or len(values) > 1025 or max(values) > 65535:
        raise ValueError('Source array exceeds fixture bounds')
    ident = re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()
    lines.append(f'const {ident}: [u32; {len(values)}] = [' + ','.join(map(str, values)) + '];')
for name in ('Rec709RGBToLMS', 'LMSToICtCp', 'ICtCpToLMS', 'LMSToRec709RGB'):
    matches = re.findall(r'static const struct NvKmsCscMatrix ' + name + r' = \{\{(.*?)\}\};', text, re.S)
    if len(matches) != 1:
        raise ValueError('Missing/ambiguous source matrix: ' + name)
    values = [int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\b0\b', matches[0])]
    if len(values) != 12 or max(values) > 0x1fffff:
        raise ValueError('Source matrix exceeds coefficient bounds')
    values = [v if v < 0x100000 else v - 0x200000 for v in values]
    lines.append(f'const {name.upper()}: [i32; 12] = [' + ','.join(map(str, values)) + '];')
output.write_text('\n'.join(lines) + '\n')
